"""Generate `_cased_table.py`: the code points whose case-insensitive match can differ from a
plain code-point test, as ranges. Built once per (Python, Unicode) pair instead of at every
import (Reviewer B, revision 4, NIT 8: computing it at import cost 1.16 s per process).

    python gen_cased.py            # write the table
    python gen_cased.py --check    # CI: fail if the committed table is stale
"""
import re
import sys
import unicodedata


def compute() -> list[int]:
    cps = set()
    for cp in range(sys.maxunicode + 1):
        ch = chr(cp)
        lo, up, cf = ch.lower(), ch.upper(), ch.casefold()
        if lo != ch or up != ch or cf != ch:
            cps.add(cp)
        for c in (lo, up):
            if len(c) == 1 and c != ch:
                cps.add(ord(c))
    for k, vs in getattr(re._compiler, "_ignorecase_fixes", {}).items():
        cps.update((k, *vs))
    return sorted(cps)


def ranges(points):
    out, start, prev = [], None, None
    for cp in points:
        if start is None:
            start = prev = cp
        elif cp == prev + 1:
            prev = cp
        else:
            out.append((start, prev))
            start = prev = cp
    if start is not None:
        out.append((start, prev))
    return out


def word_runs() -> list[int]:
    """Code points where `re`'s \\w membership flips, starting from U+0000 (which is not \\w).

    A range is all-word or all-non-word exactly when no flip falls strictly inside it, which a
    bisect over this list answers in O(log n) (Reviewer A, revision 5: probing each range by
    building its characters cost 986 ms for 166 wide ranges)."""
    flips, prev = [], False
    w = re.compile(r"\w")
    for cp in range(sys.maxunicode + 1):
        cur = w.match(chr(cp)) is not None
        if cur != prev:
            flips.append(cp)
            prev = cur
    return flips


def render() -> str:
    rs = ranges(compute())
    body = ",\n".join(f"    (0x{a:05x}, 0x{b:05x})" for a, b in rs)
    flips = word_runs()
    fbody = ",\n".join("    " + ", ".join(f"0x{c:05x}" for c in flips[i:i + 8]) for i in range(0, len(flips), 8))
    return (
        "# Generated by gen_cased.py. Do not edit.\n"
        f"PYTHON = {sys.version_info[:2]!r}\nUNICODE = {unicodedata.unidata_version!r}\n"
        f"CASED_RANGES = (\n{body},\n)\n"
        f"WORD_FLIPS = (\n{fbody},\n)\n"
    )


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        current = open("_cased_table.py", encoding="utf-8").read()
        sys.exit(0 if current == text else "stale _cased_table.py: regenerate it")
    open("_cased_table.py", "w", encoding="utf-8").write(text)
    print("ranges:", text.count("(0x"))
