// WCAG 2.1 contrast check for every direction x theme x pair in tokens.mjs.
// Exit code 1 if any pair is below its floor. Writes contrast-report.md next to it.
import fs from "node:fs";
import { directions, pairs } from "./tokens.mjs";

function lum(hex) {
  const n = hex.replace("#", "");
  const [r, g, b] = [0, 2, 4].map((i) => parseInt(n.slice(i, i + 2), 16) / 255);
  const lin = (c) => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4);
  return 0.2126 * lin(r) + 0.7152 * lin(g) + 0.0722 * lin(b);
}
export function ratio(a, b) {
  const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p);
  return (x + 0.05) / (y + 0.05);
}

let fails = 0;
const lines = ["# Contrast report (generated by check-contrast.mjs)", "", "| Direction | Theme | Pair | Use | Ratio | Floor | Result |", "|---|---|---|---|---|---|---|"];
for (const [key, d] of Object.entries(directions)) {
  for (const [theme, t] of Object.entries(d.themes)) {
    for (const [fg, bg, floor, use] of pairs) {
      const r = ratio(t[fg], t[bg]);
      const ok = r >= floor;
      if (!ok) fails++;
      lines.push(`| ${d.title} | ${theme} | \`${fg}\` ${t[fg]} on \`${bg}\` ${t[bg]} | ${use} | ${r.toFixed(2)} | ${floor} | ${ok ? "pass" : "FAIL"} |`);
      if (!ok) console.log(`FAIL ${key}/${theme}: ${fg} ${t[fg]} on ${bg} ${t[bg]} = ${r.toFixed(2)} < ${floor}`);
    }
  }
}
lines.push("", `Total pairs: ${lines.length - 4}, failures: ${fails}`);
fs.writeFileSync(new URL("./contrast-report.md", import.meta.url), lines.join("\n") + "\n");
console.log(`pairs checked: ${lines.length - 6}, failures: ${fails}`);
process.exit(fails ? 1 : 0);
