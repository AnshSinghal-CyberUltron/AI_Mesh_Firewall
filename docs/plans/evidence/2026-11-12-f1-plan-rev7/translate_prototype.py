def _cased_points() -> list[int]:
    if CASED_RANGES is not None and PYTHON == sys.version_info[:2]:
        return [cp for a, b in CASED_RANGES for cp in range(a, b + 1)]
    import gen_cased  # stale or missing table: compute (slow path, never in production)
    return gen_cased.compute()


_CASED = _cased_points()
# Every cased code point once, in one string: a single-character pattern's verdict on all of them
# is one findall. Surrogates are never cased, so the string is always valid.
_CASED_STR = "".join(chr(cp) for cp in _CASED)


_CASED_LO = [a for a, _b in (CASED_RANGES or ())]
_CASED_HI = [b for _a, b in (CASED_RANGES or ())]
_CASED_BEFORE = [0]  # cased code points in the runs before run i
for _a, _b in CASED_RANGES or ():
    _CASED_BEFORE.append(_CASED_BEFORE[-1] + _b - _a + 1)
_BMP_MAX = 0xFFFF


def _cased_upto(x: int) -> int:
    """Cased code points <= x, in O(log n)."""
    i = bisect.bisect_right(_CASED_LO, x)  # runs starting at or before x
    if i == 0:
        return 0
    return _CASED_BEFORE[i - 1] + min(x, _CASED_HI[i - 1]) - _CASED_LO[i - 1] + 1


def _cased_pieces(a: int, b: int) -> list[tuple[int, int]]:
    """The cased runs inside [a, b] (b <= U+FFFF), by bisect over the build-time table."""
    i = bisect.bisect_left(_CASED_HI, a)
    out = []
    while i < len(_CASED_LO) and _CASED_LO[i] <= b:
        out.append((max(a, _CASED_LO[i]), min(b, _CASED_HI[i])))
        i += 1
    return out


_MERGE_GAP = 16  # non-cased code points bridged between clipped runs: fewer members for `re` to parse


def _merge(pieces: list[tuple[int, int]]) -> list[tuple[int, int]]:
    """The union of clipped pieces, bridging a gap of at most `_MERGE_GAP` code points only when it
    holds no cased code point (a bridged non-cased code point leaves every cased verdict unchanged;
    a cased one would ADD a member: two ranges of the item can leave out a cased code point between
    them, as `[\u0222-\u0262\u0264-\u13f7]` leaves out U+0263). At most one piece per cased run of
    the table (131), whatever the item lists."""
    out: list[tuple[int, int]] = []
    for x, y in sorted(pieces):
        if out and x <= out[-1][1] + 1:
            out[-1] = (out[-1][0], max(out[-1][1], y))
        elif (out and x <= out[-1][1] + 1 + _MERGE_GAP
              and _cased_upto(x - 1) == _cased_upto(out[-1][1])):
            out[-1] = (out[-1][0], max(out[-1][1], y))
        else:
            out.append((x, y))
    return out


def _range_verdict_units(a: int, b: int) -> int:
    """Work `re` does to fold a case-insensitive range in `_ci_verdicts` (revision 7): one unit per
    cased code point of a clipped BMP-only range, the BMP width of a range that runs into the astral
    planes (kept whole), one for an astral-only range (`re` tails it without iterating)."""
    if a > _BMP_MAX:
        return 1
    if b > _BMP_MAX:
        return _BMP_MAX + 1 - a
    return 1 + _cased_upto(b) - _cased_upto(a - 1)


def _set_source(items, clip: bool = False) -> str:
    """The set as `re` source (categories as escapes), for asking `re` its own verdict.

    With `clip` (revision 7, the verdict source), each BMP-only range is replaced by the cased runs
    it covers, each written as a RANGE (never a literal: `re` treats an astral LITERAL differently,
    see `_ci_patch_points`). That leaves `re`'s verdict on every cased code point unchanged:
    `_optimize_charset` sets `charmap[fixup(i)]` for every i of a range, and for i outside the cased
    table fixup(i) == i, which is no cased code point's lowercase (the lowercase of a cased code
    point is cased), and the extra folds (`_EXTRA_CASES`) are all cased; `iscased` implies cased, so
    `hascased` is unchanged too. Each property is checked over every code point by
    `gen_cased.py --check` (`clip_properties`). A range that runs from the BMP into the astral planes
    is kept whole: `re` puts it in the set's tail as RANGE_UNI_IGNORE, whose upper-case test reaches 5
    code points the clipped form would miss. An empty clipped set gets the non-cased member U+0000."""
    out = []
    clipped: list[tuple[int, int]] = []
    for op, av in items:
        if op is C.NEGATE:
            continue
        if op is C.LITERAL:
            out.append(_esc(av))
        elif op is C.RANGE and clip and av[1] <= _BMP_MAX:
            clipped.extend(_cased_pieces(av[0], av[1]))
        elif op is C.RANGE:
            out.append(f"{_esc(av[0])}-{_esc(av[1])}")
        elif op is C.CATEGORY:
            out.append({C.CATEGORY_DIGIT: r"\d", C.CATEGORY_NOT_DIGIT: r"\D",
                        C.CATEGORY_WORD: r"\w", C.CATEGORY_NOT_WORD: r"\W",
                        C.CATEGORY_SPACE: r"\s", C.CATEGORY_NOT_SPACE: r"\S"}[av])
        else:
            raise Refused(f"unsupported set item {op}")
    out.extend(f"{_esc(x)}-{_esc(y)}" for x, y in _merge(clipped))
    neg = any(op is C.NEGATE for op, _ in items)
    if not out:
        out.append("\\x00-\\x00")
    return "[" + ("^" if neg else "") + "".join(out) + "]"


def verdict_source(items) -> str:
    """The source `_ci_verdicts` gives `re` for a case-insensitive item (revision 7)."""
    return _set_source(items, clip=True)


#: Cost model of one case-insensitive item's verdict and patch, in microseconds of thread CPU on the
#: 12 Nov host (revision 7; calibrated and validated by ci_model7.py, LIMITS7.md section 1). A base
#: per item: a literal; a set; a heavy item (negated, with a category, or covering more than
#: `_LIGHT_POINTS` cased code points), whose verdict is scanned by runs. Then each member, by kind
#: (`regex` checks a case-insensitive range or category member at every one of the 2,927 cased code
#: points), and each code point `re` folds: the cased code points of a clipped range, and the BMP
#: width of a range that runs into the astral planes (kept whole).
_UNIT_LITERAL, _UNIT_SET, _UNIT_HEAVY = 300, 500, 1800
_UNIT_LIT_MEMBER, _UNIT_RANGE_MEMBER, _UNIT_CAT_MEMBER = 40, 180, 400
_FOLDS_PER_UNIT = 6
_LIGHT_POINTS = 64


def _is_heavy(items) -> bool:
    covered = 0
    for op, av in items:
        if op is C.NEGATE or op is C.CATEGORY:
            return True
        if op is C.RANGE:
            covered += _range_verdict_units(av[0], av[1])
        else:
            covered += 1
    return covered > _LIGHT_POINTS


def _ci_units(items) -> int:
    """Upper bound, in the cost model's microseconds, on one case-insensitive item's verdict and
    patch (revision 7). Parse-only: bisects over the cased table, never asks `re` or `regex`."""
    members = [(op, av) for op, av in items if op is not C.NEGATE]
    if _is_heavy(items):
        units = _UNIT_HEAVY
    elif len(members) == 1 and members[0][0] is C.LITERAL and len(items) == 1:
        units = _UNIT_LITERAL
    else:
        units = _UNIT_SET
    folded = 0
    for op, av in members:
        if op is C.RANGE:
            units += _UNIT_RANGE_MEMBER
            folded += _range_verdict_units(av[0], av[1])
        elif op is C.CATEGORY:
            units += _UNIT_CAT_MEMBER
        else:
            units += _UNIT_LIT_MEMBER
            folded += 1
    return units + folded // _FOLDS_PER_UNIT


def _ci_items_of(item_source: str):
    """The case-insensitive item `item_source` (one literal or set) as parsed items (for tests)."""
    (op, av), = list(_parse("(?i)" + item_source))
    if op is C.IN:
        return av
    return [(C.LITERAL, av)] if op is C.LITERAL else [(C.NEGATE, None), (C.LITERAL, av)]


def _parts(items):
    neg = False
    plain, cats = [], []
    for op, av in items:
        if op is C.NEGATE:
            neg = True
        elif op is C.LITERAL:
            plain.append(_esc(av))
        elif op is C.RANGE and av[0] == av[1]:
            plain.append(_esc(av[0]))  # a one-code-point range is a literal (see _build)
        elif op is C.RANGE:
            plain.append(f"{_esc(av[0])}-{_esc(av[1])}")
        elif op is C.CATEGORY:
            cats.append(_POS[av])
        else:
            raise Refused(f"unsupported set item {op}")
    return neg, "".join(plain), tuple(cats)


_ONE_ESCAPE = re.compile(r"\\(?:x[0-9a-f]{2}|u[0-9a-f]{4}|U[0-9a-f]{8})")
_ESCAPES = re.compile(r"\\(?:x([0-9a-f]{2})|u([0-9a-f]{4})|U([0-9a-f]{8}))(?:-\\(?:x([0-9a-f]{2})|u([0-9a-f]{4})|U([0-9a-f]{8})))?")


def _one_code_point(plain: str) -> str | None:
    """The escape of the single code point `plain` covers, or None (plain is our own emission)."""
    points = set()
    for m in _ESCAPES.finditer(plain):
        a = int(m.group(1) or m.group(2) or m.group(3), 16)
        b = int(m.group(4) or m.group(5) or m.group(6) or "%x" % a, 16)
        points.add((a, b))
        if len(points) > 1 or a != b:
            return None
    return _esc(points.pop()[0]) if points else None


def _neg_plain(plain: str) -> str:
    """Members of a negated set, never ONE code point.

    `regex` (2023.8.8 and 2026.9.29) merges alternatives that are negated sets of one code point
    into ONE negated set, turning (?:[^9]|[^c]) into [^9c] (an intersection of the complements, not
    their union): it under-matches, a bypass. It fires through non-capturing groups, with astral
    members and with one-code-point ranges (`[^a-a]`, revision 6). A repeated member keeps the set
    a set, and is exact for every engine since a set is unchanged by a duplicate member. Every
    negated set the translator emits passes through here."""
    one = _one_code_point(plain)
    return one + one if one is not None else plain


def _build(neg: bool, plain: str, cats: tuple, icase: bool) -> str:
    """Set text. Categories never fold case (as in `re`); plain members fold when `icase`."""
    def wrap(text: str) -> str:
        return f"(?i:{text})" if icase else text
    if neg and not cats:
        plain = _neg_plain(plain)
    if not cats:
        return wrap(f"[{'^' if neg else ''}{plain}]")
    if not plain and len(cats) == 1 and not neg:
        return cats[0]
    if not plain and len(cats) == 1 and cats[0] in _COMPLEMENT:
        return _COMPLEMENT[cats[0]]
    alts = ([wrap(f"[{plain}]")] if plain else []) + list(cats)
    member = "(?:" + "|".join(alts) + ")"
    return f"(?:(?!{member})(?s:.))" if neg else member


def _cs_set(items) -> str:
    return _build(*_parts(items), icase=False)


def _scan_cased(pattern: str, engine, runs: bool) -> frozenset[str]:
    """The cased code points a one-character item (`pattern`, with its flags) matches.

    Revision 7: a heavy item (`_is_heavy`: negated, with a category, or covering many cased code
    points) is scanned by RUNS, one match per run of matching code points (`(?:X)+`), so the scan
    stays in C instead of building one Python match per cased code point (a negated item cost
    1.4-2 ms per item that way in revision 6). The item consumes one character and reads no context,
    so the runs cover exactly the code points it matches. A light item is scanned per code point,
    where the engines' literal prefix search is faster."""
    if runs:
        return frozenset("".join(engine.findall("(?:" + pattern + ")+", _CASED_STR)))
    return frozenset(engine.findall(pattern, _CASED_STR))


@lru_cache(maxsize=4096)
def _ci_verdicts(source: str, runs: bool = True) -> frozenset[str]:
    """The cased code points `re` matches for `(?i)source` (a one-character item). `source` is the
    clipped verdict source (`verdict_source`): its cost is bounded by `_ci_units` (revision 7)."""
    _check_budget()
    out = _scan_cased("(?i)" + source if not runs else "(?i:" + source + ")", re, runs)
    _check_budget()
    return out


@lru_cache(maxsize=4096)
def _ci_set(source: str, neg: bool, plain: str, cats: tuple, runs: bool = True) -> str:
    """Case-insensitive set or literal with `re`'s exact verdict on every cased code point.

    Native `regex` case folding is kept wherever it agrees with `re` (the common case); the code
    points where it does not are added or removed explicitly.
    """
    native = _build(neg, plain, cats, icase=True)
    want = _ci_verdicts(source, runs)
    have = _scan_cased(native, regex, runs)
    _check_budget()
    missing = want - have
    if missing:
        # Revision 6: `regex`'s first-character prefilter can hide a code point from the plain scan
        # above (`(?:(?i:[_])|\W)` misses U+0345) that the item DOES match inside the translated
        # pattern, whose leading guard disables that prefilter. Such a point is matched through the
        # unfolded categories, so `re` wants it too: re-check only the missing points behind the guard,
        # so the patch holds just the points where the engines really differ (the size estimate
        # relies on it; a full guarded scan costs 14x more).
        missing -= frozenset(regex.findall(_PREFILTER_GUARD + native, "".join(sorted(missing))))
    add = sorted(ord(c) for c in missing)
    drop = sorted(ord(c) for c in have - want)
    core = native
    if drop:
        core = f"(?![{_body(drop)}]){core}"
    if add:
        core = f"(?:[{_body(add)}]|{core})"
    return core


_MODE = threading.local()  # .estimate: emit size placeholders instead of asking `regex`
_FOLD_DISAGREE = frozenset(FOLD_DISAGREE or ())


def _ci_patch_points(items) -> set[int]:
    """Every code point `_ci_set` can patch into this case-insensitive item (revision 6).

    Two sources, both measured (estimate_test.py; 20,000 random sets, 0 outside this set):
    * FOLD_DISAGREE, the 10 code points where the engines' folding differs (I, i, U+0130, U+0131,
      U+0390, U+03B0, U+1FD3, U+1FE3, U+FB05, U+FB06), when a member covers one of them;
    * an astral LITERAL member and its case partners: CPython 3.12's `re` drops an astral literal
      from a multi-member case-insensitive set (`(?i)[\\U0001e91c\\x41]` does not match U+1E91C;
      `_compiler._optimize_charset` keeps it unfolded in the tail), and the translator keeps that.
    Every other member folds identically in both engines, and categories are not folded."""
    pts: set[int] = set()
    for op, av in items:
        if op is C.LITERAL:
            if av in _FOLD_DISAGREE:
                pts |= _FOLD_DISAGREE
            if av > 0xFFFF:
                ch = chr(av)
                pts |= {av} | {ord(x) for x in (ch.lower(), ch.upper()) if len(x) == 1}
        elif op is C.RANGE and any(av[0] <= c <= av[1] for c in _FOLD_DISAGREE):
            pts |= _FOLD_DISAGREE
    return pts


def _ci_patch_bound(items) -> int:
    """Largest number of characters `_ci_set` can add to the native text: the patch is
    `(?:[add]|(?![drop])native)` with add and drop disjoint subsets of `_ci_patch_points`, each
    point costing its escape plus at most one '-', plus 13 characters of syntax."""
    pts = _ci_patch_points(items)
    return sum(len(_esc(c)) + 1 for c in pts) + 13 if pts else 0


def _ci_item(items) -> str:
    """A case-insensitive literal or set: `re`'s exact verdict (translation), or, in estimate mode,
    the native text padded by the largest patch `_ci_set` can add (so never smaller than the real
    text, and computed without `regex`)."""
    neg, plain, cats = _parts(items)
    if not getattr(_MODE, "estimate", False):
        return _ci_set(verdict_source(items), neg, plain, cats, _is_heavy(items))
    native = _build(neg, plain, cats, icase=True)
    bound = _ci_patch_bound(items)
    return "(?:" + native + "#" * (bound - 4) + ")" if bound else native


_ATOM = re.compile(r"(?:\\[xuU][0-9a-f]+|\\[pP]\{\w+\}|\[(?:\\.|[^\\\]\[])*\])", re.ASCII)


def _atomic(text: str) -> bool:
    """One char, one escape, one property or one bracket set: safe to quantify unwrapped."""
    return len(text) == 1 or _ATOM.fullmatch(text) is not None


