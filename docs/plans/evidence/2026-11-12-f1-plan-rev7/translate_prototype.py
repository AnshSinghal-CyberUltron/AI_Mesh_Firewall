"""Translate a Python `re` pattern into a `regex` pattern that matches exactly what `re` matches.

Revision 5 of the F1a-1 prototype. The pattern is parsed by `re`'s own parser, so escapes, sets,
verbose mode, scoped flags and quantifier syntax mean what `re` says they mean. The tree is
re-emitted for `regex`, replacing every construct whose meaning differs between the engines:

* \\d \\w \\s and negations: property classes equal to `re`'s on the pinned (Python, regex) pair;
* \\b \\B: lookarounds over that \\w. When the neighbouring item can only start (or end) with a
  word character, or only with a non-word character, ONE side is already known and a one-sided
  lookaround is emitted (exact, and 100-1000x faster than the two-sided form next to a class);
  \\B is false on the empty string, as in `re`;
* case-insensitive literals and sets: `re`'s own verdict on every cased code point is taken, so its
  simple case folding and its special fixes (i/ı/İ, k/K, s/ſ, ...) are kept exactly. The verdict
  is one `findall` over a string of all cased code points (not one call per code point);
* `.`, `^`, `$`: emitted with explicit scoped flags, so no global flag reaches `regex`.

Refused: the ASCII and LOCALE flags, backreferences under IGNORECASE, and patterns over the
publish-time cost limits (`check_limits`).

Revision 6 (Reviewer B, revision 5):
* a group-nesting limit, checked by an iterative scan BEFORE `re._parser` runs (a 499-deep pattern
  raised RecursionError out of `re`, `check_limits`, `translate` and `stopper`);
* every entry point turns ANY exception from parsing, translating or compiling into `Refused`;
* a parse-only size estimate (`Analysis.translated_size`, `Analysis.compile_units`) bounds the
  translated text and `regex`'s compile work, which unrolls the minimum count of every repeat
  (nested `+` doubled the compiled program per level: 16 levels took 0.2-0.3 s, 32 levels ran
  the host out of memory) and expands `\\s`, two-sided `\\b` and case-insensitive items;
* a negated set that covers ONE code point is always emitted with two members, however it was
  written (`[^a-a]` was not, and `(?:[^a-a]|[^b-b])` under-matched through `regex`'s merge bug).

Revision 7 (Plan Reviewers A and B, revision 6):
* a group that no backreference or conditional names is emitted non-capturing, and references are
  renumbered (B blocker 1: `regex` keeps every capture of a repeated group, so `(\\w)*` grew by
  112 MiB per 512 KiB pass; captures never change a match's span);
* the case-insensitive verdict asks `re` about each BMP-only range CLIPPED to the cased code points
  it covers (A blocker 1: `re` folds every code point of a range, so a 65,536-wide range cost 5 ms
  and a legal plan 3.7 s). Exact: a code point outside the cased table is its own lowercase and is
  no cased code point's lowercase, and `re`'s extra folds stay inside the table (checked over every
  code point by `gen_cased.py --check`). A range that runs from the BMP into the astral planes is
  kept whole (its tail is matched by `RANGE_UNI_IGNORE`, whose upper-case test differs for 5 code
  points) and is charged its BMP width;
* the translation CPU budget is checked before every item and inside the verdict, not only on entry
  to a sequence (A blocker 1: a flat pattern checked it twice);
* the parse-only estimate counts the verdict's work (`ci_units`), capped per rule and per plan, so
  the three callers refuse the same rules and the CPU cap is a safety net that accepted rules do not
  reach.

`analyze` also returns the pattern's read reach: how far right of a match's start an attempt can
read. A finite reach lets a streaming scan resume instead of rescanning the whole output.
"""
