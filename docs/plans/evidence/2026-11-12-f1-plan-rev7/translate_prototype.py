def _chars_class(chars) -> str | None:
    """'w' when every char is in re's \\w, 'n' when none is, None when mixed or empty."""
    text = "".join(chars)
    if not text:
        return None
    has_w = _WORD_RE.search(text) is not None
    has_n = _NONWORD_RE.search(text) is not None
    return None if has_w and has_n else ("w" if has_w else "n")


def _word_flips() -> list[int]:
    if WORD_FLIPS is not None and PYTHON == sys.version_info[:2]:
        return list(WORD_FLIPS)
    import gen_cased  # stale or missing table: compute (slow path, never in production)
    return gen_cased.word_runs()


_FLIPS = _word_flips()


def _range_class(a: int, b: int) -> str | None:
    """O(log n): a range is one class exactly when no \\w flip falls in (a, b]."""
    i = bisect.bisect_right(_FLIPS, a)       # flips at or before a
    if i < len(_FLIPS) and _FLIPS[i] <= b:   # a flip inside the range: mixed
        return None
    return "w" if i % 2 == 1 else "n"        # an odd number of flips so far: inside a word run


def _join(classes) -> str | None:
    classes = set(classes)
    return classes.pop() if len(classes) == 1 and None not in classes else None


def _set_class(items, icase: bool) -> str | None:
    if any(op is C.NEGATE for op, _ in items):
        return None
    out = []
    for op, av in items:
        if op is C.LITERAL:
            out.append(_chars_class(chr(av)))
        elif op is C.RANGE:
            out.append(_range_class(*av))
        elif op is C.CATEGORY:
            out.append({C.CATEGORY_DIGIT: "w", C.CATEGORY_WORD: "w",
                        C.CATEGORY_SPACE: "n", C.CATEGORY_NOT_WORD: "n"}.get(av))
        else:
            return None
    if icase:  # the case variants `re` adds are cased code points: classify them too
        variants = _ci_verdicts(verdict_source(items), _is_heavy(items))
        if variants:
            out.append(_chars_class(variants))
    return _join(out)


def _item_class(op, av, flags: int, side: str) -> str | None:
    icase = bool(flags & C.SRE_FLAG_IGNORECASE)
    if op is C.LITERAL:
        return _set_class([(C.LITERAL, av)], icase)
    if op is C.IN:
        return _set_class(av, icase)
    if op is C.SUBPATTERN:
        _group, add, dele, p = av
        return _edge_class(p, (flags | add) & ~dele, side)
    if op is C.ATOMIC_GROUP:
        return _edge_class(av, flags, side)
    if op in (C.MAX_REPEAT, C.MIN_REPEAT, C.POSSESSIVE_REPEAT):
        lo, _hi, item = av
        return _edge_class(item, flags, side) if lo >= 1 else None
    if op is C.BRANCH:
        return _join(_edge_class(alt, flags, side) for alt in av[1])
    return None  # ANY, NOT_LITERAL, assertions, group references: mixed or zero-width


def _edge_class(sub, flags: int, side: str) -> str | None:
    """Class of the first (side='first') or last character a non-empty match of `sub` consumes."""
    items = list(sub)
    if not items:
        return None
    op, av = items[0] if side == "first" else items[-1]
    return _item_class(op, av, flags, side)


def _boundary(at, items, i: int, flags: int) -> str:
    nxt = _item_class(*items[i + 1], flags, "first") if i + 1 < len(items) else None
    if nxt is not None:
        return _ONE_SIDED[(at, "next", nxt)]
    prv = _item_class(*items[i - 1], flags, "last") if i > 0 else None
    if prv is not None:
        return _ONE_SIDED[(at, "prev", prv)]
    return _BOUNDARY if at is C.AT_BOUNDARY else _NON_BOUNDARY


# --- emission --------------------------------------------------------------------------------

_SINGLE = (C.LITERAL, C.NOT_LITERAL, C.IN, C.ANY)


def _possessive_safe(items, i: int, flags: int) -> bool:
    r"""A greedy repeat of one character class X can be emitted atomically (no backtracking)
    when the next item must start with a character X cannot match: giving back any character
    leaves an X character next, where that item cannot start, so backtracking never succeeds.
    The classes are compared at word/non-word granularity; `\b` after X requires the next
    character to be of the other class, so it qualifies too. Exact, and it removes the
    per-word backtracking that made `\b\w+\s+(?:token|secret)\b` 4x slower than `re`."""
    op, av = items[i]
    if op is not C.MAX_REPEAT or i + 1 >= len(items):
        return False
    lo, _hi, item = av
    inner = list(item)
    if len(inner) != 1 or inner[0][0] not in _SINGLE:
        return False
    cx = _item_class(*inner[0], flags, "first")
    if cx is None:
        return False
    nop, nav = items[i + 1]
    if nop is C.AT and nav is C.AT_BOUNDARY:
        # `\b` compares the characters on BOTH sides; giving back every X moves the left side
        # out of the run, so this holds only while at least one X must stay (fuzz: `1{,2}\b`).
        return lo >= 1
    cy = _item_class(nop, nav, flags, "first")
    return cy is not None and cy != cx


_BUDGET = threading.local()
#: Per-rule translation CPU cap (Reviewer A, revision 5): a rule that needs more is refused, so a
#: shape the limits do not count cannot hold a gateway worker. Measured worst legal rule: see perf5.
TRANSLATE_CPU_BUDGET_S = 0.05


def _check_budget() -> None:
    deadline = getattr(_BUDGET, "deadline", None)
    if deadline is not None and time.thread_time() > deadline:
        raise Refused("translation exceeded its CPU budget")


def _emit(sub, flags: int, out: list[str]) -> None:
    _check_budget()
    items = list(sub)
    for i, (op, av) in enumerate(items):
        _check_budget()  # revision 7: per item, so a flat sequence cannot pass the cap unchecked
        if op is C.AT and av in (C.AT_BOUNDARY, C.AT_NON_BOUNDARY):
            out.append(_boundary(av, items, i, flags))
        elif _possessive_safe(items, i, flags):
            inner: list[str] = []
            _emit_one(op, av, flags, inner)
            out.append("(?>" + "".join(inner) + ")")
        else:
            _emit_one(op, av, flags, out)


def _emit_one(op, av, flags: int, out: list[str]) -> None:
    icase = bool(flags & C.SRE_FLAG_IGNORECASE)
    if op is C.LITERAL or op is C.NOT_LITERAL:
        items = [(C.LITERAL, av)] if op is C.LITERAL else [(C.NEGATE, None), (C.LITERAL, av)]
        if icase:
            out.append(_ci_item(items))
        elif op is C.LITERAL:
            out.append(_esc(av))
        else:
            out.append(_cs_set(items))  # never a lone negated character (see _neg_plain)
    elif op is C.ANY:
        out.append("(?s:.)" if flags & C.SRE_FLAG_DOTALL else "(?-s:.)")
    elif op is C.IN:
        out.append(_ci_item(av) if icase else _cs_set(av))
    elif op is C.BRANCH:
        out.append("(?:")
        for i, alt in enumerate(av[1]):
            if i:
                out.append("|")
            _emit(alt, flags, out)
        out.append(")")
    elif op is C.SUBPATTERN:
        group, add, dele, p = av
        if (add | dele) & (C.SRE_FLAG_ASCII | C.SRE_FLAG_LOCALE):
            raise Refused("ASCII and LOCALE flags are not supported")
        inner = (flags | add) & ~dele
        # Revision 7: only a group that a backreference or a conditional names captures.
        out.append("(" if group is not None and group in _renumber() else "(?:")
        _emit(p, inner, out)
        out.append(")")
    elif op in (C.MAX_REPEAT, C.MIN_REPEAT, C.POSSESSIVE_REPEAT):
        lo, hi, item = av
        inner: list[str] = []
        _emit(item, flags, inner)
        text = "".join(inner)
        q = {(0, C.MAXREPEAT): "*", (1, C.MAXREPEAT): "+", (0, 1): "?"}.get((lo, hi))
        q = q or "{%d,%s}" % (lo, "" if hi is C.MAXREPEAT else hi)
        if op is C.POSSESSIVE_REPEAT:
            # `re` never backtracks into a possessive repeat NOR into any one of its iterations;
            # `regex`'s `X{m,n}+` backtracks inside an iteration (Reviewer A, revision 4:
            # `(?:a+x?){2,}+` on "aaa"). Both levels are made atomic explicitly.
            out.append(f"(?>(?>{text}){q})")
            return
        out.append(text if _atomic(text) else f"(?:{text})")
        out.append(q)
        if op is C.MIN_REPEAT:
            out.append("?")
    elif op is C.ATOMIC_GROUP:
        out.append("(?>")
        _emit(av, flags, out)
        out.append(")")
    elif op is C.AT:
        multiline = bool(flags & C.SRE_FLAG_MULTILINE)
        out.append({
            C.AT_BEGINNING: "(?m:^)" if multiline else "(?-m:^)",
            C.AT_END: "(?m:$)" if multiline else "(?-m:$)",
            C.AT_BEGINNING_STRING: "\\A",
            C.AT_END_STRING: "\\Z",
            C.AT_BOUNDARY: _BOUNDARY,
            C.AT_NON_BOUNDARY: _NON_BOUNDARY,
        }[av])
    elif op in (C.ASSERT, C.ASSERT_NOT):
        _check_lookbehind(av)
        direction, p = av
        out.append({(C.ASSERT, 1): "(?=", (C.ASSERT, -1): "(?<=",
                    (C.ASSERT_NOT, 1): "(?!", (C.ASSERT_NOT, -1): "(?<!"}[(op, direction)])
        _emit(p, flags, out)
        out.append(")")
    elif op is C.GROUPREF:
        if icase:
            raise Refused("a backreference under IGNORECASE is not supported")
        out.append(f"(?:\\g<{_renumber()[av]}>)")
    elif op is C.GROUPREF_EXISTS:
        group, yes, no = av
        out.append(f"(?({_renumber()[group]})")
        _emit(yes, flags, out)
        if no is not None:
            out.append("|")
            _emit(no, flags, out)
        out.append(")")
    else:
        raise Refused(f"unsupported construct {op}")


_GROUPS = threading.local()  # .renumber: {source group number: emitted group number}


def _renumber() -> dict[int, int]:
    return getattr(_GROUPS, "renumber", None) or {}


def _referenced(sub, acc: set, open_groups: frozenset = frozenset()) -> None:
    """Group numbers a backreference or a conditional names (revision 7).

    Refuses a reference to a group from inside that group (`(a\\1)`, `(?P<g>(?(g)x|y))`): `re` and
    `regex` disagree there (17 of 20,760 checks in `renumber_test.py`, revision 6 and 7 alike), and
    `re` has no defined value for a group that has not closed yet."""
    for op, av in sub:
        if op is C.GROUPREF:
            if av in open_groups:
                raise Refused("a reference to a group from inside that group is not supported")
            acc.add(av)
        elif op is C.GROUPREF_EXISTS:
            if av[0] in open_groups:
                raise Refused("a conditional on a group from inside that group is not supported")
            acc.add(av[0])
            _referenced(av[1], acc, open_groups)
            if av[2] is not None:
                _referenced(av[2], acc, open_groups)
        elif op is C.SUBPATTERN:
            g = av[0]
            _referenced(av[3], acc, open_groups | {g} if g is not None else open_groups)
        elif op is C.ATOMIC_GROUP:
            _referenced(av, acc, open_groups)
        elif op is C.BRANCH:
            for alt in av[1]:
                _referenced(alt, acc, open_groups)
        elif op in (C.ASSERT, C.ASSERT_NOT):
            _referenced(av[1], acc, open_groups)
        elif op in (C.MAX_REPEAT, C.MIN_REPEAT, C.POSSESSIVE_REPEAT):
            _referenced(av[2], acc, open_groups)


def _group_map(parsed) -> dict[int, int]:
    """Referenced groups keep capturing, renumbered in source order (every source group is emitted
    exactly once, in order, so the k-th kept group is the k-th capturing group of the output)."""
    refs: set[int] = set()
    _referenced(parsed, refs)
    return {g: k for k, g in enumerate(sorted(refs), start=1)}


# --- group nesting, scanned without recursion (Reviewer B, revision 5, blocker 2) -------------

_WHITESPACE = frozenset(" \t\n\r\v\f")
_FLAGS = frozenset("aiLmsux")


def group_depth(pattern: str, limit: int | None = None) -> int:
    """The deepest group nesting `re._parser` will recurse into, found by an iterative scan.

    It follows `re._parser` token by token: a backslash and the next character are one token;
    a set runs to the first `]` after at least one member; `(?#...)` runs to the first `)`;
    in verbose mode (a global `(?x)` at the start, or a scoped `(?x:...)`) whitespace is skipped
    and `#` starts a comment to the end of the line; `(?P=name)` and global flags open no group;
    a conditional `(?(...)` opens one. So the count is exact for every pattern `re` accepts, and
    for any other pattern it is exact up to the point where `re` stops with an error. O(n), no
    recursion. Returns early once the depth exceeds `limit`.
    """
    s, n = pattern, len(pattern)

    def tok(i: int) -> tuple[str, int]:
        if s[i] == "\\":
            return s[i:i + 2], i + 2
        return s[i], i + 1

    depth = deepest = 0
    verbose = [False]  # verbose state of each open group; [0] is the top level
    i = 0
    while i < n:
        t, i = tok(i)
        if verbose[-1]:
            if t in _WHITESPACE:
                continue
            if t == "#":
                while i < n:
                    t, i = tok(i)
                    if t == "\n":
                        break
                continue
        if t == "[":
            if i < n and s[i] == "^":
                i += 1
            members = 0
            while i < n:
                t, i = tok(i)
                if t == "]" and members:
                    break
                members += 1
            continue
        if t == ")":
            if depth == 0:
                return deepest  # unbalanced: `re` stops here
            depth -= 1
            verbose.pop()
            continue
        if t != "(":
            continue
        sub = verbose[-1]
        if i < n and s[i] == "?":
            if i + 1 >= n:
                return deepest
            c, i = tok(i + 1)
            if c == "P":
                if i < n and s[i] in "<=":
                    end = ">" if s[i] == "<" else ")"
                    opens = s[i] == "<"
                    i += 1
                    while i < n:
                        t, i = tok(i)
                        if t == end:
                            break
                    if not opens:
                        continue  # (?P=name): a backreference
                else:
                    return deepest
            elif c == "#":
                while i < n:
                    t, i = tok(i)
                    if t == ")":
                        break
                continue
            elif c == "(":
                while i < n:  # the condition, up to its ')'
                    t, i = tok(i)
                    if t == ")":
                        break
            elif c == "<":
                if i >= n or s[i] not in "=!":
                    return deepest
                i += 1
            elif c in _FLAGS or c == "-":
                add, rem, cur, t = set(), set(), None, c
                cur = rem if t == "-" else add
                if t != "-":
                    add.add(t)
                while i < n:
                    t, i = tok(i)
                    if t in (")", ":"):
                        break
                    if t == "-":
                        cur = rem
                    else:
                        cur.add(t)
                else:
                    return deepest
                if t == ")":  # global flags: only valid at the start of the top level
                    verbose[0] = verbose[0] or "x" in add
                    continue
                sub = (sub or "x" in add) and "x" not in rem
            elif c not in ":>=!":
                return deepest
        depth += 1
        verbose.append(sub)
        if depth > deepest:
            deepest = depth
            if limit is not None and deepest > limit:
                return deepest
    return deepest


#: Deepest group nesting accepted (revision 6). `regex.compile` needs up to 18 Python frames per
#: level of the translated pattern (`(?i:a|...)*+` nests, measured), so a 16-deep rule needs at most
#: about 300 frames: it compiles even from a caller already 600 frames deep (the default recursion
#: limit is 1000). 32 levels needed 586 frames, and failed from 600 deep.
MAX_DEPTH = 16


def _parse(pattern: str):
    """`re._parser.parse`, after the nesting check (the parse itself recurses per level)."""
    d = group_depth(pattern, MAX_DEPTH)
    if d > MAX_DEPTH:
        raise Refused(f"groups nested deeper than {MAX_DEPTH}")
    return P.parse(pattern, 0)


# --- analysis: cost limits and read reach -----------------------------------------------------

INF = float("inf")


@dataclass(frozen=True)
class Analysis:
    length: int
    expanded_repetition: int  # sum over counted repeats of bound x enclosing product
    nested_product: int       # largest product of nested counted repeats
    ci_items: int             # distinct case-insensitive literals/sets (each costs one verdict)
    min_width: int
    reach: float              # max chars right of a match start an attempt can read (INF: unbounded)
    depth: int = 0            # deepest group nesting (iterative scan, before parsing)
    translated_size: int = 0  # upper bound on len(translate(pattern)), parse-only (revision 6)
    compile_units: int = 0    # upper bound on compile_units(translate(pattern)), parse-only
    ci_units: int = 0         # case-insensitive verdict work (revision 7): see `_ci_units`


_MAXCODE = getattr(re._compiler, "MAXCODE", 0xFFFFFFFF)


def _check_lookbehind(av) -> None:
    """`re` refuses a variable-width lookbehind when it COMPILES the pattern (`_compiler.py:150-155`),
    after parsing succeeds; `regex` would accept it. Refuse it here, so the parse-only check refuses
    every pattern `re.compile` refuses (revision 6: `(?<=a+)b` passed check_limits and translated)."""
    direction, p = av
    if direction < 0:
        lo, hi = p.getwidth()
        if lo > _MAXCODE:
            raise Refused("looks too much behind")
        if lo != hi:
            raise Refused("look-behind requires fixed-width pattern")


def _counted(lo: int, hi: int) -> int | None:
    if (lo, hi) in ((0, 1), (0, C.MAXREPEAT), (1, C.MAXREPEAT)):
        return None
    return lo if hi is C.MAXREPEAT else hi


def _walk(sub, flags: int, product: int, acc: dict) -> None:
    for op, av in sub:
        icase = bool(flags & C.SRE_FLAG_IGNORECASE)
        if op in (C.LITERAL, C.NOT_LITERAL) and icase:
            if ("L", op, av) not in acc["ci"]:
                acc["ci"].add(("L", op, av))
                lit = [(C.LITERAL, av)] if op is C.LITERAL else [(C.NEGATE, None), (C.LITERAL, av)]
                acc["ci_units"] += _ci_units(lit)
        elif op is C.IN and icase:
            key = ("S", _set_source(av))
            if key not in acc["ci"]:
                acc["ci"].add(key)
                acc["ci_units"] += _ci_units(av)
        elif op is C.SUBPATTERN:
            _g, add, dele, p = av
            _walk(p, (flags | add) & ~dele, product, acc)
        elif op is C.ATOMIC_GROUP:
            _walk(av, flags, product, acc)
        elif op is C.BRANCH:
            for alt in av[1]:
                _walk(alt, flags, product, acc)
        elif op in (C.ASSERT, C.ASSERT_NOT):
            _check_lookbehind(av)
            _walk(av[1], flags, product, acc)
        elif op is C.GROUPREF_EXISTS:
            _walk(av[1], flags, product, acc)
            if av[2] is not None:
                _walk(av[2], flags, product, acc)
        elif op in (C.MAX_REPEAT, C.MIN_REPEAT, C.POSSESSIVE_REPEAT):
            lo, hi, item = av
            n = _counted(lo, hi)
            inner = product
            if n is not None:
                inner = product * max(n, 1)
                acc["expanded"] += inner
                acc["nested"] = max(acc["nested"], inner)
            _walk(item, flags, inner, acc)


def _reach(sub, flags: int) -> tuple[float, float]:
    """(max width, max read) of a sequence, measured from its start; INF when unbounded."""
    pos = 0.0
    read = 0.0
    for op, av in sub:
        w, r = _item_reach(op, av, flags)
        read = max(read, pos + r)
        pos += w
    return pos, read


def _item_reach(op, av, flags: int) -> tuple[float, float]:
    if op in (C.LITERAL, C.NOT_LITERAL, C.IN, C.ANY):
        return 1, 1
    if op is C.SUBPATTERN:
        _g, add, dele, p = av
        return _reach(p, (flags | add) & ~dele)
    if op is C.ATOMIC_GROUP:
        return _reach(av, flags)
    if op is C.BRANCH:
        rs = [_reach(alt, flags) for alt in av[1]]
        return max(w for w, _ in rs), max(r for _, r in rs)
    if op in (C.MAX_REPEAT, C.MIN_REPEAT, C.POSSESSIVE_REPEAT):
        lo, hi, item = av
        if hi is C.MAXREPEAT:
            return INF, INF
        if hi == 0:
            return 0, 0
        w, r = _reach(item, flags)
        if hi == 1:
            return w, r
        return hi * w, (hi - 1) * w + r
    if op in (C.ASSERT, C.ASSERT_NOT):
        direction, p = av
        if direction > 0:
            return 0, _reach(p, flags)[1]
        # A lookbehind reads left, unless something inside it reads right of its end (a nested
        # lookahead, a boundary or an end anchor): then the reach is not bounded here.
        return (0, INF) if _reads_right(p) else (0, 0)
    if op is C.AT:
        if av in (C.AT_BOUNDARY, C.AT_NON_BOUNDARY, C.AT_END_STRING):
            return 0, 1
        if av is C.AT_END:
            return 0, (1 if flags & C.SRE_FLAG_MULTILINE else 2)
        return 0, 0  # ^ and \A read to the left only
    if op is C.GROUPREF_EXISTS:
        _g, yes, no = av
        a = _reach(yes, flags)
        b = _reach(no, flags) if no is not None else (0, 0)
        return max(a[0], b[0]), max(a[1], b[1])
    return INF, INF  # GROUPREF and anything else: unbounded (never wrong, only not incremental)


def _reads_right(sub) -> bool:
    for op, av in sub:
        if op is C.AT and av in (C.AT_BOUNDARY, C.AT_NON_BOUNDARY, C.AT_END, C.AT_END_STRING):
            return True
        if op in (C.ASSERT, C.ASSERT_NOT) and (av[0] > 0 or _reads_right(av[1])):
            return True
        if op is C.SUBPATTERN and _reads_right(av[3]):
            return True
        if op is C.ATOMIC_GROUP and _reads_right(av):
            return True
        if op is C.BRANCH and any(_reads_right(alt) for alt in av[1]):
            return True
        if op in (C.MAX_REPEAT, C.MIN_REPEAT, C.POSSESSIVE_REPEAT) and _reads_right(av[2]):
            return True
        if op is C.GROUPREF_EXISTS and (_reads_right(av[1]) or (av[2] is not None and _reads_right(av[2]))):
            return True
    return False


@_refusing
def analyze(pattern: str) -> Analysis:
    depth = group_depth(pattern, MAX_DEPTH)
    parsed = _parse(pattern)
    flags = parsed.state.flags
    acc = {"expanded": 0, "nested": 1, "ci": set(), "ci_units": 0}
    _walk(parsed, flags, 1, acc)
    if acc["ci_units"] > MAX_CI_UNITS:
        # Refused before the estimate walk, which asks `re` for the same verdicts: so the parse-only
        # check's own cost is bounded by the cap (revision 7).
        raise Refused(f"case-insensitive verdict units {acc['ci_units']} over {MAX_CI_UNITS}")
    lo, _hi = parsed.getwidth()
    _w, reach = _reach(parsed, flags)
    est = _estimate_text(parsed)
    return Analysis(len(pattern), acc["expanded"], acc["nested"], len(acc["ci"]), lo, reach,
                    depth, len(est), compile_units(est), acc["ci_units"])


def _estimate_text(parsed) -> str:
    """The translation, with every `regex`-dependent case-insensitive patch replaced by padding of
    its largest possible size: so len() and compile_units() of this text bound the real
    translation's, and computing it needs only `re` (the parse-only check imports no `regex`).
    Deterministic: no CPU timer, so the projector, control and the gateway agree."""
    flags = parsed.state.flags
    if flags & (C.SRE_FLAG_ASCII | C.SRE_FLAG_LOCALE):
        raise Refused("ASCII and LOCALE flags are not supported")
    _MODE.estimate = True
    saved = getattr(_BUDGET, "deadline", None)
    saved_map = getattr(_GROUPS, "renumber", None)
    _BUDGET.deadline = None
    _GROUPS.renumber = _group_map(parsed)
    try:
        out: list[str] = []
        _emit(parsed, flags, out)
    finally:
        _MODE.estimate = False
        _BUDGET.deadline = saved
        _GROUPS.renumber = saved_map
    text = "".join(out)
    return _PREFILTER_GUARD + text if "(?i:" in text else text


# --- compile units: what `regex.compile` builds -------------------------------------------------

_GROUP_OPEN = re.compile(r"\((?:\?(?:[:>=!]|<[=!]|[ims]*-?[ims]*:|\(\d+\)))?")
_ATOM_TOKEN = re.compile(r"\\(?:x[0-9a-f]{2}|u[0-9a-f]{4}|U[0-9a-f]{8}|[pP]\{\w+\}|g<\d+>|.)"
                         r"|\[\^?(?:\\(?:x[0-9a-f]{2}|u[0-9a-f]{4}|U[0-9a-f]{8}|[pP]\{\w+\}|.)|[^\]\\])*\]"
                         r"|[^()|*+?{]", re.ASCII)
_QUANT = re.compile(r"(?:([*+?])|\{(\d+)(?:(,)(\d*))?\})\??")


def _copies(lo: int, hi: float) -> int:
    """How many times `regex`'s compiler builds a repeat's body (`build_REPEAT` in _regex.c): the
    minimum count is unrolled, plus one looping copy when the maximum is larger. `X{1}` is built
    once; `X*`, `X?` and `X{0,n}` once; `X+` twice; `X{3}` three times; `X{2,5}` three times."""
    if lo <= 1 and hi == lo:
        return 1
    if lo == 0:
        return 1
    return lo + (0 if hi == lo else 1)


def compile_units(text: str) -> int:
    """Characters of translated text, each multiplied by how many times `regex`'s compiler builds
    it: the product of `_copies` over the repeats around it (revision 6).

    `regex` unrolls every repeat's minimum count at compile time, so nested repeats multiply the
    compiled program: `(?:(?:a)+)+...` 16 deep built 2**16 bodies (0.2-0.3 s and 113-181 MiB in one
    C call that holds the GIL), 32 deep exhausted the host's memory. The translator emits a fixed
    vocabulary (escapes, sets, groups, quantifiers), so one iterative scan reads it. Also accepts the
    estimate text, whose '#' padding counts one unit per character."""
    stack = [0]
    i, n = 0, len(text)
    while i < n:
        c = text[i]
        if c == "(":
            m = _GROUP_OPEN.match(text, i)
            stack.append(m.end() - i)
            i = m.end()
            continue
        if c == "|":
            stack[-1] += 1
            i += 1
            continue
        if c == ")":
            size = stack.pop() + 1
            i += 1
        else:
            m = _ATOM_TOKEN.match(text, i)
            if m is None:
                raise Refused(f"unexpected translator output at {i}")
            size = m.end() - i
            i = m.end()
        q = _QUANT.match(text, i)
        if q:
            if q.group(1):
                lo, hi = {"*": (0, INF), "+": (1, INF), "?": (0, 1)}[q.group(1)]
            else:
                lo = int(q.group(2))
                hi = INF if q.group(3) and not q.group(4) else int(q.group(4)) if q.group(4) else lo
            size *= _copies(lo, hi)
            i = q.end()
        stack[-1] += size
    if len(stack) != 1:
        raise Refused("unbalanced translator output")
    return stack[0]


# Publish-time limits. Revision 4 had length and per-repeat/nested bounds; revision 5 adds the
# total expanded repetition (B: "x{1000}"*140 compiled in 92 ms and +36 MiB) and the number of
# distinct case-insensitive items (B: 996 distinct items took 2.2 s to translate).
MAX_LENGTH = 1000
MAX_REPEAT_COUNT = 1000
MAX_NESTED_PRODUCT = 1000
MAX_EXPANDED_REPETITION = 1000
MAX_CI_ITEMS = 64
# Revision 6 (Reviewer B, revision 5, should-fix 4, and the nested-repeat compile bomb): bounds on
# the translated text (Python-side parse and compile cost, linear in it) and on the compile units
# (`regex`'s C-side build, which holds the GIL). Chosen from perf6.md; see LIMITS6.md.
MAX_TRANSLATED_SIZE = 16_384
MAX_COMPILE_UNITS = 32_768
MAX_PLAN_TRANSLATED_SIZE = 131_072
MAX_PLAN_COMPILE_UNITS = 262_144
MAX_PLAN_CI_ITEMS = 512
# Revision 7 (Plan Reviewer A, revision 6, blocker 1): the case-insensitive verdict's folding work,
# counted parse-only (`Analysis.ci_units`). See LIMITS7.md for the cost per unit.
MAX_CI_UNITS = 24_000        # about 24 ms of the cost model per rule: under half the 50 ms CPU cap
MAX_PLAN_CI_UNITS = 96_000


@_refusing
def check_limits(pattern: str) -> Analysis:
    if len(pattern) > MAX_LENGTH:
        raise Refused(f"pattern longer than {MAX_LENGTH}")
    a = analyze(pattern)
    if a.nested_product > MAX_NESTED_PRODUCT:
        raise Refused(f"nested counted repetition over {MAX_NESTED_PRODUCT}")
    if a.expanded_repetition > MAX_EXPANDED_REPETITION:
        raise Refused(f"total counted repetition over {MAX_EXPANDED_REPETITION}")
    if a.ci_items > MAX_CI_ITEMS:
        raise Refused(f"more than {MAX_CI_ITEMS} distinct case-insensitive items")
    if a.translated_size > MAX_TRANSLATED_SIZE:
        raise Refused(f"translated size {a.translated_size} over {MAX_TRANSLATED_SIZE}")
    if a.compile_units > MAX_COMPILE_UNITS:
        raise Refused(f"compile units {a.compile_units} over {MAX_COMPILE_UNITS}")
    if a.ci_units > MAX_CI_UNITS:
        raise Refused(f"case-insensitive verdict units {a.ci_units} over {MAX_CI_UNITS}")
    return a


def check_plan(patterns) -> dict[str, Analysis | Refused]:
    """The parse-only check of a plan's regex rules: each rule, then the per-plan sums. A rule over a
    per-rule limit is refused on its own; when the accepted rules' sums exceed a per-plan limit, the
    rules are refused from the last one back until the sums fit (a deterministic order, so control,
    the projector and the gateway refuse the same rules)."""
    out: dict[str, Analysis | Refused] = {}
    for p in patterns:
        try:
            out[p] = check_limits(p)
        except Refused as e:
            out[p] = e
    accepted = [p for p in out if isinstance(out[p], Analysis)]
    def sums(ps):
        return (sum(out[p].translated_size for p in ps), sum(out[p].compile_units for p in ps),
                sum(out[p].ci_items for p in ps), sum(out[p].ci_units for p in ps))
    while accepted:
        size, units, ci, ciu = sums(accepted)
        if (size <= MAX_PLAN_TRANSLATED_SIZE and units <= MAX_PLAN_COMPILE_UNITS
                and ci <= MAX_PLAN_CI_ITEMS and ciu <= MAX_PLAN_CI_UNITS):
            break
        last = accepted.pop()
        out[last] = Refused(f"plan over its limits (translated size {size}, compile units {units}, "
                            f"case-insensitive items {ci}, verdict units {ciu})")
    return out


@_refusing
def compile_rule(pattern: str, cpu_budget_s: float | None = TRANSLATE_CPU_BUDGET_S):
    """The gateway path: the limits, translation and `regex.compile`; any failure is `Refused`.
    The translated text is checked against the same caps (never larger than the estimate, which
    the limits already bounded: a failure here is a translator bug, refused and counted)."""
    a = check_limits(pattern)
    text = translate(pattern, cpu_budget_s)
    if len(text) > a.translated_size or compile_units(text) > a.compile_units:
        raise Refused("translation larger than its parse-only estimate")
    return regex.compile(text)


@_refusing
def translate(pattern: str, cpu_budget_s: float | None = TRANSLATE_CPU_BUDGET_S) -> str:
    _BUDGET.deadline = None if cpu_budget_s is None else time.thread_time() + cpu_budget_s
    try:
        return _translate(pattern)
    finally:
        _BUDGET.deadline = None


def _translate(pattern: str) -> str:
    parsed = _parse(pattern)
    flags = parsed.state.flags
    if flags & (C.SRE_FLAG_ASCII | C.SRE_FLAG_LOCALE):
        raise Refused("ASCII and LOCALE flags are not supported")
    out: list[str] = []
    saved_map = getattr(_GROUPS, "renumber", None)
    _GROUPS.renumber = _group_map(parsed)
    try:
        _emit(parsed, flags, out)
    finally:
        _GROUPS.renumber = saved_map
    text = "".join(out)
    # `regex` builds a first-character prefilter for a pattern; when the pattern starts with an
    # optional case-insensitive item, that prefilter folds the FOLLOWING case-sensitive set too
    # and skips positions `re` matches (measured: `(?i:a)?[^\p{L}]` misses U+0345). A leading
    # always-true lookahead with an alternation disables that prefilter.
    return _PREFILTER_GUARD + text if "(?i:" in text else text


_PREFILTER_GUARD = r"(?=[\s\S]|\Z)"


# --- stopper class: characters no consuming item of the pattern can match ------------------

def _collect(sub, flags: int, acc: list) -> bool:
    """Collect (op, av, flags) of every single-character consumer; False if end-sensitive."""
    for op, av in sub:
        if op in _SINGLE:
            acc.append((op, av, flags))
        elif op is C.SUBPATTERN:
            _g, add, dele, p = av
            if not _collect(p, (flags | add) & ~dele, acc):
                return False
        elif op is C.ATOMIC_GROUP:
            if not _collect(av, flags, acc):
                return False
        elif op is C.BRANCH:
            for alt in av[1]:
                if not _collect(alt, flags, acc):
                    return False
        elif op in (C.MAX_REPEAT, C.MIN_REPEAT, C.POSSESSIVE_REPEAT):
            if not _collect(av[2], flags, acc):
                return False
        elif op in (C.ASSERT, C.ASSERT_NOT):
            _check_lookbehind(av)
            if not _collect(av[1], flags, acc):
                return False
        elif op is C.GROUPREF_EXISTS:
            if not _collect(av[1], flags, acc) or (av[2] is not None and not _collect(av[2], flags, acc)):
                return False
        elif op is C.AT and (av is C.AT_END_STRING or (av is C.AT_END and not flags & C.SRE_FLAG_MULTILINE)):
            return False  # `\Z` and `$` read the end of the text, which moves as the text grows
    return True


@_refusing
def stopper(pattern: str) -> str | None:
    """A `regex` class matching exactly the characters no consuming item can match, or None.

    An attempt cannot consume a stopper, and every assertion it evaluates sits at or before the
    first stopper at or after its start, so once a stopper follows position t the outcome of the
    attempt at t is final. `\\Z` and non-multiline `$` read the end of the text: no stopper.
    """
    parsed = _parse(pattern)
    acc: list = []
    if not _collect(parsed, parsed.state.flags, acc):
        return None
    if any(op is C.ANY and fl & C.SRE_FLAG_DOTALL for op, _av, fl in acc):
        return None
    parts: list[str] = []
    for op, av, fl in acc:
        _emit_one(op, av, fl, parts)
    if not parts:
        return None
    return "(?:(?!(?:" + "|".join(dict.fromkeys(parts)) + "))(?s:.))"
