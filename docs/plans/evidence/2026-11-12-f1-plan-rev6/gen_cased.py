"""Generate `_cased_table.py`: the code points whose case-insensitive match can differ from a
plain code-point test, as ranges. Built once per (Python, Unicode) pair instead of at every
import (Reviewer B, revision 4, NIT 8: computing it at import cost 1.16 s per process).

    python gen_cased.py            # write the table
    python gen_cased.py --check    # CI: fail if the committed table is stale
"""
import re
import sys
import unicodedata


def compute() -> list[int]:
    cps = set()
    for cp in range(sys.maxunicode + 1):
        ch = chr(cp)
        lo, up, cf = ch.lower(), ch.upper(), ch.casefold()
        if lo != ch or up != ch or cf != ch:
            cps.add(cp)
        for c in (lo, up):
            if len(c) == 1 and c != ch:
                cps.add(ord(c))
    for k, vs in getattr(re._compiler, "_ignorecase_fixes", {}).items():
        cps.update((k, *vs))
    return sorted(cps)


def ranges(points):
    out, start, prev = [], None, None
    for cp in points:
        if start is None:
            start = prev = cp
        elif cp == prev + 1:
            prev = cp
        else:
            out.append((start, prev))
            start = prev = cp
    if start is not None:
        out.append((start, prev))
    return out


def word_runs() -> list[int]:
    """Code points where `re`'s \\w membership flips, starting from U+0000 (which is not \\w).

    A range is all-word or all-non-word exactly when no flip falls strictly inside it, which a
    bisect over this list answers in O(log n) (Reviewer A, revision 5: probing each range by
    building its characters cost 986 ms for 166 wide ranges)."""
    flips, prev = [], False
    w = re.compile(r"\w")
    for cp in range(sys.maxunicode + 1):
        cur = w.match(chr(cp)) is not None
        if cur != prev:
            flips.append(cp)
            prev = cur
    return flips


def fold_disagreement(cased: list[int]) -> list[int]:
    """Cased code points where `re`'s case-insensitive verdict for some single literal differs from
    `regex`'s native folding (revision 6). The translator patches exactly these code points into a
    case-insensitive item (`_ci_set`'s add/drop sets are subsets of this list), so the parse-only
    size estimate can bound that patch without importing `regex`. The set is closed under both
    engines' folding: a literal or range that contains none of these code points gets no patch.
    Needs `regex` (the pinned one) at build time only."""
    import regex
    text = "".join(chr(c) for c in cased)

    def esc(c: int) -> str:
        return f"\\U{c:08x}"

    out: set[int] = set()
    for cp in cased:
        want = set(re.findall("(?i)" + esc(cp), text))
        have = set(regex.findall("(?i:[" + esc(cp) + "])", text))
        out |= {ord(c) for c in want ^ have}
    closure = set(out)
    every = "".join(chr(c) for c in range(sys.maxunicode + 1) if not 0xD800 <= c <= 0xDFFF)
    for cp in out:  # close under both engines' folding (in practice it is already closed)
        closure |= {ord(c) for c in re.findall("(?i)" + esc(cp), every)}
        closure |= {ord(c) for c in regex.findall("(?i:[" + esc(cp) + "])", every)}
    return sorted(closure)


def render() -> str:
    cased = compute()
    rs = ranges(cased)
    body = ",\n".join(f"    (0x{a:05x}, 0x{b:05x})" for a, b in rs)
    flips = word_runs()
    fbody = ",\n".join("    " + ", ".join(f"0x{c:05x}" for c in flips[i:i + 8]) for i in range(0, len(flips), 8))
    return (
        "# Generated by gen_cased.py. Do not edit.\n"
        f"PYTHON = {sys.version_info[:2]!r}\nUNICODE = {unicodedata.unidata_version!r}\n"
        f"CASED_RANGES = (\n{body},\n)\n"
        f"WORD_FLIPS = (\n{fbody},\n)\n"
        f"FOLD_DISAGREE = ({', '.join(f'0x{c:05x}' for c in fold_disagreement(cased))},)\n"
    )


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        current = open("_cased_table.py", encoding="utf-8").read()
        sys.exit(0 if current == text else "stale _cased_table.py: regenerate it")
    open("_cased_table.py", "w", encoding="utf-8").write(text)
    print("ranges:", text.count("(0x"))
