"""Translate a Python `re` pattern into a `regex` pattern that matches exactly what `re` matches.

Revision 5 of the F1a-1 prototype. The pattern is parsed by `re`'s own parser, so escapes, sets,
verbose mode, scoped flags and quantifier syntax mean what `re` says they mean. The tree is
re-emitted for `regex`, replacing every construct whose meaning differs between the engines:

* \\d \\w \\s and negations: property classes equal to `re`'s on the pinned (Python, regex) pair;
* \\b \\B: lookarounds over that \\w. When the neighbouring item can only start (or end) with a
  word character, or only with a non-word character, ONE side is already known and a one-sided
  lookaround is emitted (exact, and 100-1000x faster than the two-sided form next to a class);
  \\B is false on the empty string, as in `re`;
* case-insensitive literals and sets: `re`'s own verdict on every cased code point is taken, so its
  simple case folding and its special fixes (i/ı/İ, k/K, s/ſ, ...) are kept exactly. The verdict
  is one `findall` over a string of all cased code points (not one call per code point);
* `.`, `^`, `$`: emitted with explicit scoped flags, so no global flag reaches `regex`.

Refused: the ASCII and LOCALE flags, backreferences under IGNORECASE, and patterns over the
publish-time cost limits (`check_limits`).

`analyze` also returns the pattern's read reach: how far right of a match's start an attempt can
read. A finite reach lets a streaming scan resume instead of rescanning the whole output.
"""
from __future__ import annotations

import re
import sys
from dataclasses import dataclass
from functools import lru_cache

import regex
from re import _constants as C
from re import _parser as P

try:
    from _cased_table import CASED_RANGES, PYTHON, UNICODE
except ImportError:  # pragma: no cover - the table is generated by gen_cased.py
    CASED_RANGES, PYTHON, UNICODE = None, None, None

__all__ = ("Analysis", "Refused", "analyze", "check_limits", "translate")


class Refused(ValueError):
    """A valid `re` pattern this translator will not serve (its meaning or cost is not bounded)."""


def _ranges(points):
    out = []
    start = prev = None
    for cp in points:
        if start is None:
            start = prev = cp
        elif cp == prev + 1:
            prev = cp
        else:
            out.append((start, prev))
            start = prev = cp
    if start is not None:
        out.append((start, prev))
    return out


def _esc(cp: int) -> str:
    if cp > 0xFFFF:
        return f"\\U{cp:08x}"
    if cp > 0xFF:
        return f"\\u{cp:04x}"
    return f"\\x{cp:02x}"


def _body(points) -> str:
    return "".join(_esc(a) if a == b else f"{_esc(a)}-{_esc(b)}" for a, b in _ranges(sorted(points)))


_W = "[\\p{L}\\p{N}_]"
_NW = "[^\\p{L}\\p{N}_]"
_D = "\\p{Nd}"
_ND = "\\P{Nd}"
_SPACE = [cp for cp in range(0x3001) if re.match(r"\s", chr(cp))]  # all of re's \s is below U+3001
_S = "[" + _body(_SPACE) + "]"
_NS = "[^" + _body(_SPACE) + "]"
_POS = {C.CATEGORY_DIGIT: _D, C.CATEGORY_WORD: _W, C.CATEGORY_SPACE: _S,
        C.CATEGORY_NOT_DIGIT: _ND, C.CATEGORY_NOT_WORD: _NW, C.CATEGORY_NOT_SPACE: _NS}
_COMPLEMENT = {_W: _NW, _NW: _W, _D: _ND, _ND: _D, _S: _NS, _NS: _S}
_BOUNDARY = f"(?:(?<={_W})(?!{_W})|(?<!{_W})(?={_W}))"
_NON_BOUNDARY = f"(?:(?<={_W})(?={_W})|(?<!{_W})(?!{_W})(?!\\A\\Z))"
# One-sided forms, used when the neighbour fixes one side (see `_boundary`).
_ONE_SIDED = {
    # (assertion, side known, class of the known char) -> lookaround on the unknown side
    (C.AT_BOUNDARY, "next", "w"): f"(?<!{_W})",
    (C.AT_BOUNDARY, "next", "n"): f"(?<={_W})",
    (C.AT_BOUNDARY, "prev", "w"): f"(?!{_W})",
    (C.AT_BOUNDARY, "prev", "n"): f"(?={_W})",
    (C.AT_NON_BOUNDARY, "next", "w"): f"(?<={_W})",
    (C.AT_NON_BOUNDARY, "next", "n"): f"(?<!{_W})",
    (C.AT_NON_BOUNDARY, "prev", "w"): f"(?={_W})",
    (C.AT_NON_BOUNDARY, "prev", "n"): f"(?!{_W})",
}


def _cased_points() -> list[int]:
    if CASED_RANGES is not None and PYTHON == sys.version_info[:2]:
        return [cp for a, b in CASED_RANGES for cp in range(a, b + 1)]
    import gen_cased  # stale or missing table: compute (slow path, never in production)
    return gen_cased.compute()


_CASED = _cased_points()
# Every cased code point once, in one string: a single-character pattern's verdict on all of them
# is one findall. Surrogates are never cased, so the string is always valid.
_CASED_STR = "".join(chr(cp) for cp in _CASED)


def _set_source(items) -> str:
    """The set as `re` source (categories as escapes), for asking `re` its own verdict."""
    out = []
    for op, av in items:
        if op is C.NEGATE:
            continue
        if op is C.LITERAL:
            out.append(_esc(av))
        elif op is C.RANGE:
            out.append(f"{_esc(av[0])}-{_esc(av[1])}")
        elif op is C.CATEGORY:
            out.append({C.CATEGORY_DIGIT: r"\d", C.CATEGORY_NOT_DIGIT: r"\D",
                        C.CATEGORY_WORD: r"\w", C.CATEGORY_NOT_WORD: r"\W",
                        C.CATEGORY_SPACE: r"\s", C.CATEGORY_NOT_SPACE: r"\S"}[av])
        else:
            raise Refused(f"unsupported set item {op}")
    neg = any(op is C.NEGATE for op, _ in items)
    return "[" + ("^" if neg else "") + "".join(out) + "]"


def _parts(items):
    neg = False
    plain, cats = [], []
    for op, av in items:
        if op is C.NEGATE:
            neg = True
        elif op is C.LITERAL:
            plain.append(_esc(av))
        elif op is C.RANGE:
            plain.append(f"{_esc(av[0])}-{_esc(av[1])}")
        elif op is C.CATEGORY:
            cats.append(_POS[av])
        else:
            raise Refused(f"unsupported set item {op}")
    return neg, "".join(plain), tuple(cats)


_ONE_ESCAPE = re.compile(r"\\(?:x[0-9a-f]{2}|u[0-9a-f]{4}|U[0-9a-f]{8})")


def _build(neg: bool, plain: str, cats: tuple, icase: bool) -> str:
    """Set text. Categories never fold case (as in `re`); plain members fold when `icase`."""
    def wrap(text: str) -> str:
        return f"(?i:{text})" if icase else text
    if neg and _ONE_ESCAPE.fullmatch(plain):
        # `regex` (2023.8.8 and 2026.9.29) merges alternatives that are lone negated
        # characters into ONE negated set, turning (?:[^9]|[^c]) into [^9c] (an intersection
        # of the complements, not their union): it under-matches. A repeated member keeps the
        # set a set. Exact for every engine, since a set is unchanged by a duplicate member.
        plain = plain + plain
    if not cats:
        return wrap(f"[{'^' if neg else ''}{plain}]")
    if not plain and len(cats) == 1 and not neg:
        return cats[0]
    if not plain and len(cats) == 1 and cats[0] in _COMPLEMENT:
        return _COMPLEMENT[cats[0]]
    alts = ([wrap(f"[{plain}]")] if plain else []) + list(cats)
    member = "(?:" + "|".join(alts) + ")"
    return f"(?:(?!{member})(?s:.))" if neg else member


def _cs_set(items) -> str:
    return _build(*_parts(items), icase=False)


@lru_cache(maxsize=4096)
def _ci_verdicts(source: str) -> frozenset[str]:
    """The cased code points `re` matches for `(?i)source` (a one-character item): one findall."""
    return frozenset(re.findall("(?i)" + source, _CASED_STR))


@lru_cache(maxsize=4096)
def _ci_set(source: str, neg: bool, plain: str, cats: tuple) -> str:
    """Case-insensitive set or literal with `re`'s exact verdict on every cased code point.

    Native `regex` case folding is kept wherever it agrees with `re` (the common case); the code
    points where it does not are added or removed explicitly.
    """
    native = _build(neg, plain, cats, icase=True)
    want = _ci_verdicts(source)
    have = frozenset(regex.findall(native, _CASED_STR))
    add = sorted(ord(c) for c in want - have)
    drop = sorted(ord(c) for c in have - want)
    core = native
    if drop:
        core = f"(?![{_body(drop)}]){core}"
    if add:
        core = f"(?:[{_body(add)}]|{core})"
    return core


_ATOM = regex.compile(r"(?:\\[xuU][0-9a-f]+|\\[pP]\{\w+\}|\[(?:\\.|[^\\\]\[])*\])")


def _atomic(text: str) -> bool:
    """One char, one escape, one property or one bracket set: safe to quantify unwrapped."""
    return len(text) == 1 or _ATOM.fullmatch(text) is not None


# --- word-class of an item's first or last character (for one-sided boundaries) -------------

_WORD_RE = re.compile(r"\w")
_NONWORD_RE = re.compile(r"\W")
_MAX_RANGE_PROBE = 0x10000  # a wider range is classified "mixed" (never wrong, just slower)


def _chars_class(chars) -> str | None:
    """'w' when every char is in re's \\w, 'n' when none is, None when mixed or empty."""
    text = "".join(chars)
    if not text:
        return None
    has_w = _WORD_RE.search(text) is not None
    has_n = _NONWORD_RE.search(text) is not None
    return None if has_w and has_n else ("w" if has_w else "n")


@lru_cache(maxsize=4096)
def _range_class(a: int, b: int) -> str | None:
    if b - a >= _MAX_RANGE_PROBE:
        return None
    return _chars_class(chr(cp) for cp in range(a, b + 1) if not 0xD800 <= cp <= 0xDFFF)


def _join(classes) -> str | None:
    classes = set(classes)
    return classes.pop() if len(classes) == 1 and None not in classes else None


def _set_class(items, icase: bool) -> str | None:
    if any(op is C.NEGATE for op, _ in items):
        return None
    out = []
    for op, av in items:
        if op is C.LITERAL:
            out.append(_chars_class(chr(av)))
        elif op is C.RANGE:
            out.append(_range_class(*av))
        elif op is C.CATEGORY:
            out.append({C.CATEGORY_DIGIT: "w", C.CATEGORY_WORD: "w",
                        C.CATEGORY_SPACE: "n", C.CATEGORY_NOT_WORD: "n"}.get(av))
        else:
            return None
    if icase:  # the case variants `re` adds are cased code points: classify them too
        variants = _ci_verdicts(_set_source(items))
        if variants:
            out.append(_chars_class(variants))
    return _join(out)


def _item_class(op, av, flags: int, side: str) -> str | None:
    icase = bool(flags & C.SRE_FLAG_IGNORECASE)
    if op is C.LITERAL:
        return _set_class([(C.LITERAL, av)], icase)
    if op is C.IN:
        return _set_class(av, icase)
    if op is C.SUBPATTERN:
        _group, add, dele, p = av
        return _edge_class(p, (flags | add) & ~dele, side)
    if op is C.ATOMIC_GROUP:
        return _edge_class(av, flags, side)
    if op in (C.MAX_REPEAT, C.MIN_REPEAT, C.POSSESSIVE_REPEAT):
        lo, _hi, item = av
        return _edge_class(item, flags, side) if lo >= 1 else None
    if op is C.BRANCH:
        return _join(_edge_class(alt, flags, side) for alt in av[1])
    return None  # ANY, NOT_LITERAL, assertions, group references: mixed or zero-width


def _edge_class(sub, flags: int, side: str) -> str | None:
    """Class of the first (side='first') or last character a non-empty match of `sub` consumes."""
    items = list(sub)
    if not items:
        return None
    op, av = items[0] if side == "first" else items[-1]
    return _item_class(op, av, flags, side)


def _boundary(at, items, i: int, flags: int) -> str:
    nxt = _item_class(*items[i + 1], flags, "first") if i + 1 < len(items) else None
    if nxt is not None:
        return _ONE_SIDED[(at, "next", nxt)]
    prv = _item_class(*items[i - 1], flags, "last") if i > 0 else None
    if prv is not None:
        return _ONE_SIDED[(at, "prev", prv)]
    return _BOUNDARY if at is C.AT_BOUNDARY else _NON_BOUNDARY


# --- emission --------------------------------------------------------------------------------

_SINGLE = (C.LITERAL, C.NOT_LITERAL, C.IN, C.ANY)


def _possessive_safe(items, i: int, flags: int) -> bool:
    r"""A greedy repeat of one character class X can be emitted atomically (no backtracking)
    when the next item must start with a character X cannot match: giving back any character
    leaves an X character next, where that item cannot start, so backtracking never succeeds.
    The classes are compared at word/non-word granularity; `\b` after X requires the next
    character to be of the other class, so it qualifies too. Exact, and it removes the
    per-word backtracking that made `\b\w+\s+(?:token|secret)\b` 4x slower than `re`."""
    op, av = items[i]
    if op is not C.MAX_REPEAT or i + 1 >= len(items):
        return False
    lo, _hi, item = av
    inner = list(item)
    if len(inner) != 1 or inner[0][0] not in _SINGLE:
        return False
    cx = _item_class(*inner[0], flags, "first")
    if cx is None:
        return False
    nop, nav = items[i + 1]
    if nop is C.AT and nav is C.AT_BOUNDARY:
        # `\b` compares the characters on BOTH sides; giving back every X moves the left side
        # out of the run, so this holds only while at least one X must stay (fuzz: `1{,2}\b`).
        return lo >= 1
    cy = _item_class(nop, nav, flags, "first")
    return cy is not None and cy != cx


def _emit(sub, flags: int, out: list[str]) -> None:
    items = list(sub)
    for i, (op, av) in enumerate(items):
        if op is C.AT and av in (C.AT_BOUNDARY, C.AT_NON_BOUNDARY):
            out.append(_boundary(av, items, i, flags))
        elif _possessive_safe(items, i, flags):
            inner: list[str] = []
            _emit_one(op, av, flags, inner)
            out.append("(?>" + "".join(inner) + ")")
        else:
            _emit_one(op, av, flags, out)


def _emit_one(op, av, flags: int, out: list[str]) -> None:
    icase = bool(flags & C.SRE_FLAG_IGNORECASE)
    if op is C.LITERAL or op is C.NOT_LITERAL:
        items = [(C.LITERAL, av)] if op is C.LITERAL else [(C.NEGATE, None), (C.LITERAL, av)]
        if icase:
            out.append(_ci_set(_set_source(items), *_parts(items)))
        elif op is C.LITERAL:
            out.append(_esc(av))
        else:
            out.append(f"[^{_esc(av)}{_esc(av)}]")  # see _build: never a lone negated char
    elif op is C.ANY:
        out.append("(?s:.)" if flags & C.SRE_FLAG_DOTALL else "(?-s:.)")
    elif op is C.IN:
        out.append(_ci_set(_set_source(av), *_parts(av)) if icase else _cs_set(av))
    elif op is C.BRANCH:
        out.append("(?:")
        for i, alt in enumerate(av[1]):
            if i:
                out.append("|")
            _emit(alt, flags, out)
        out.append(")")
    elif op is C.SUBPATTERN:
        group, add, dele, p = av
        if (add | dele) & (C.SRE_FLAG_ASCII | C.SRE_FLAG_LOCALE):
            raise Refused("ASCII and LOCALE flags are not supported")
        inner = (flags | add) & ~dele
        out.append("(?:" if group is None else "(")
        _emit(p, inner, out)
        out.append(")")
    elif op in (C.MAX_REPEAT, C.MIN_REPEAT, C.POSSESSIVE_REPEAT):
        lo, hi, item = av
        inner: list[str] = []
        _emit(item, flags, inner)
        text = "".join(inner)
        q = {(0, C.MAXREPEAT): "*", (1, C.MAXREPEAT): "+", (0, 1): "?"}.get((lo, hi))
        q = q or "{%d,%s}" % (lo, "" if hi is C.MAXREPEAT else hi)
        if op is C.POSSESSIVE_REPEAT:
            # `re` never backtracks into a possessive repeat NOR into any one of its iterations;
            # `regex`'s `X{m,n}+` backtracks inside an iteration (Reviewer A, revision 4:
            # `(?:a+x?){2,}+` on "aaa"). Both levels are made atomic explicitly.
            out.append(f"(?>(?>{text}){q})")
            return
        out.append(text if _atomic(text) else f"(?:{text})")
        out.append(q)
        if op is C.MIN_REPEAT:
            out.append("?")
    elif op is C.ATOMIC_GROUP:
        out.append("(?>")
        _emit(av, flags, out)
        out.append(")")
    elif op is C.AT:
        multiline = bool(flags & C.SRE_FLAG_MULTILINE)
        out.append({
            C.AT_BEGINNING: "(?m:^)" if multiline else "(?-m:^)",
            C.AT_END: "(?m:$)" if multiline else "(?-m:$)",
            C.AT_BEGINNING_STRING: "\\A",
            C.AT_END_STRING: "\\Z",
            C.AT_BOUNDARY: _BOUNDARY,
            C.AT_NON_BOUNDARY: _NON_BOUNDARY,
        }[av])
    elif op in (C.ASSERT, C.ASSERT_NOT):
        direction, p = av
        out.append({(C.ASSERT, 1): "(?=", (C.ASSERT, -1): "(?<=",
                    (C.ASSERT_NOT, 1): "(?!", (C.ASSERT_NOT, -1): "(?<!"}[(op, direction)])
        _emit(p, flags, out)
        out.append(")")
    elif op is C.GROUPREF:
        if icase:
            raise Refused("a backreference under IGNORECASE is not supported")
        out.append(f"(?:\\g<{av}>)")
    elif op is C.GROUPREF_EXISTS:
        group, yes, no = av
        out.append(f"(?({group})")
        _emit(yes, flags, out)
        if no is not None:
            out.append("|")
            _emit(no, flags, out)
        out.append(")")
    else:
        raise Refused(f"unsupported construct {op}")


# --- analysis: cost limits and read reach -----------------------------------------------------

INF = float("inf")


@dataclass(frozen=True)
class Analysis:
    length: int
    expanded_repetition: int  # sum over counted repeats of bound x enclosing product
    nested_product: int       # largest product of nested counted repeats
    ci_items: int             # distinct case-insensitive literals/sets (each costs one verdict)
    min_width: int
    reach: float              # max chars right of a match start an attempt can read (INF: unbounded)


def _counted(lo: int, hi: int) -> int | None:
    if (lo, hi) in ((0, 1), (0, C.MAXREPEAT), (1, C.MAXREPEAT)):
        return None
    return lo if hi is C.MAXREPEAT else hi


def _walk(sub, flags: int, product: int, acc: dict) -> None:
    for op, av in sub:
        icase = bool(flags & C.SRE_FLAG_IGNORECASE)
        if op in (C.LITERAL, C.NOT_LITERAL) and icase:
            acc["ci"].add(("L", op, av))
        elif op is C.IN and icase:
            acc["ci"].add(("S", _set_source(av)))
        elif op is C.SUBPATTERN:
            _g, add, dele, p = av
            _walk(p, (flags | add) & ~dele, product, acc)
        elif op is C.ATOMIC_GROUP:
            _walk(av, flags, product, acc)
        elif op is C.BRANCH:
            for alt in av[1]:
                _walk(alt, flags, product, acc)
        elif op in (C.ASSERT, C.ASSERT_NOT):
            _walk(av[1], flags, product, acc)
        elif op is C.GROUPREF_EXISTS:
            _walk(av[1], flags, product, acc)
            if av[2] is not None:
                _walk(av[2], flags, product, acc)
        elif op in (C.MAX_REPEAT, C.MIN_REPEAT, C.POSSESSIVE_REPEAT):
            lo, hi, item = av
            n = _counted(lo, hi)
            inner = product
            if n is not None:
                inner = product * max(n, 1)
                acc["expanded"] += inner
                acc["nested"] = max(acc["nested"], inner)
            _walk(item, flags, inner, acc)


def _reach(sub, flags: int) -> tuple[float, float]:
    """(max width, max read) of a sequence, measured from its start; INF when unbounded."""
    pos = 0.0
    read = 0.0
    for op, av in sub:
        w, r = _item_reach(op, av, flags)
        read = max(read, pos + r)
        pos += w
    return pos, read


def _item_reach(op, av, flags: int) -> tuple[float, float]:
    if op in (C.LITERAL, C.NOT_LITERAL, C.IN, C.ANY):
        return 1, 1
    if op is C.SUBPATTERN:
        _g, add, dele, p = av
        return _reach(p, (flags | add) & ~dele)
    if op is C.ATOMIC_GROUP:
        return _reach(av, flags)
    if op is C.BRANCH:
        rs = [_reach(alt, flags) for alt in av[1]]
        return max(w for w, _ in rs), max(r for _, r in rs)
    if op in (C.MAX_REPEAT, C.MIN_REPEAT, C.POSSESSIVE_REPEAT):
        lo, hi, item = av
        if hi is C.MAXREPEAT:
            return INF, INF
        if hi == 0:
            return 0, 0
        w, r = _reach(item, flags)
        if hi == 1:
            return w, r
        return hi * w, (hi - 1) * w + r
    if op in (C.ASSERT, C.ASSERT_NOT):
        direction, p = av
        if direction > 0:
            return 0, _reach(p, flags)[1]
        # A lookbehind reads left, unless something inside it reads right of its end (a nested
        # lookahead, a boundary or an end anchor): then the reach is not bounded here.
        return (0, INF) if _reads_right(p) else (0, 0)
    if op is C.AT:
        if av in (C.AT_BOUNDARY, C.AT_NON_BOUNDARY, C.AT_END_STRING):
            return 0, 1
        if av is C.AT_END:
            return 0, (1 if flags & C.SRE_FLAG_MULTILINE else 2)
        return 0, 0  # ^ and \A read to the left only
    if op is C.GROUPREF_EXISTS:
        _g, yes, no = av
        a = _reach(yes, flags)
        b = _reach(no, flags) if no is not None else (0, 0)
        return max(a[0], b[0]), max(a[1], b[1])
    return INF, INF  # GROUPREF and anything else: unbounded (never wrong, only not incremental)


def _reads_right(sub) -> bool:
    for op, av in sub:
        if op is C.AT and av in (C.AT_BOUNDARY, C.AT_NON_BOUNDARY, C.AT_END, C.AT_END_STRING):
            return True
        if op in (C.ASSERT, C.ASSERT_NOT) and (av[0] > 0 or _reads_right(av[1])):
            return True
        if op is C.SUBPATTERN and _reads_right(av[3]):
            return True
        if op is C.ATOMIC_GROUP and _reads_right(av):
            return True
        if op is C.BRANCH and any(_reads_right(alt) for alt in av[1]):
            return True
        if op in (C.MAX_REPEAT, C.MIN_REPEAT, C.POSSESSIVE_REPEAT) and _reads_right(av[2]):
            return True
        if op is C.GROUPREF_EXISTS and (_reads_right(av[1]) or (av[2] is not None and _reads_right(av[2]))):
            return True
    return False


def analyze(pattern: str) -> Analysis:
    parsed = P.parse(pattern, 0)
    flags = parsed.state.flags
    acc = {"expanded": 0, "nested": 1, "ci": set()}
    _walk(parsed, flags, 1, acc)
    lo, _hi = parsed.getwidth()
    _w, reach = _reach(parsed, flags)
    return Analysis(len(pattern), acc["expanded"], acc["nested"], len(acc["ci"]), lo, reach)


