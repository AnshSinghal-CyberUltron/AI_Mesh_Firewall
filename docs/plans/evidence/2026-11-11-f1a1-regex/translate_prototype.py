# distinct case-insensitive items (B: 996 distinct items took 2.2 s to translate).
MAX_LENGTH = 1000
MAX_REPEAT_COUNT = 1000
MAX_NESTED_PRODUCT = 1000
MAX_EXPANDED_REPETITION = 1000
MAX_CI_ITEMS = 64


def check_limits(pattern: str) -> Analysis:
    if len(pattern) > MAX_LENGTH:
        raise Refused(f"pattern longer than {MAX_LENGTH}")
    a = analyze(pattern)
    if a.nested_product > MAX_NESTED_PRODUCT:
        raise Refused(f"nested counted repetition over {MAX_NESTED_PRODUCT}")
    if a.expanded_repetition > MAX_EXPANDED_REPETITION:
        raise Refused(f"total counted repetition over {MAX_EXPANDED_REPETITION}")
    if a.ci_items > MAX_CI_ITEMS:
        raise Refused(f"more than {MAX_CI_ITEMS} distinct case-insensitive items")
    return a


def translate(pattern: str) -> str:
    parsed = P.parse(pattern, 0)
    flags = parsed.state.flags
    if flags & (C.SRE_FLAG_ASCII | C.SRE_FLAG_LOCALE):
        raise Refused("ASCII and LOCALE flags are not supported")
    out: list[str] = []
    _emit(parsed, flags, out)
    text = "".join(out)
    # `regex` builds a first-character prefilter for a pattern; when the pattern starts with an
    # optional case-insensitive item, that prefilter folds the FOLLOWING case-sensitive set too
    # and skips positions `re` matches (measured: `(?i:a)?[^\p{L}]` misses U+0345). A leading
    # always-true lookahead with an alternation disables that prefilter.
    return r"(?=[\s\S]|\Z)" + text if "(?i:" in text else text


# --- stopper class: characters no consuming item of the pattern can match ------------------

def _collect(sub, flags: int, acc: list) -> bool:
    """Collect (op, av, flags) of every single-character consumer; False if end-sensitive."""
    for op, av in sub:
        if op in _SINGLE:
            acc.append((op, av, flags))
        elif op is C.SUBPATTERN:
            _g, add, dele, p = av
            if not _collect(p, (flags | add) & ~dele, acc):
                return False
        elif op is C.ATOMIC_GROUP:
            if not _collect(av, flags, acc):
                return False
        elif op is C.BRANCH:
            for alt in av[1]:
                if not _collect(alt, flags, acc):
                    return False
        elif op in (C.MAX_REPEAT, C.MIN_REPEAT, C.POSSESSIVE_REPEAT):
            if not _collect(av[2], flags, acc):
                return False
        elif op in (C.ASSERT, C.ASSERT_NOT):
            if not _collect(av[1], flags, acc):
                return False
        elif op is C.GROUPREF_EXISTS:
            if not _collect(av[1], flags, acc) or (av[2] is not None and not _collect(av[2], flags, acc)):
                return False
        elif op is C.AT and (av is C.AT_END_STRING or (av is C.AT_END and not flags & C.SRE_FLAG_MULTILINE)):
            return False  # `\Z` and `$` read the end of the text, which moves as the text grows
    return True


def stopper(pattern: str) -> str | None:
    """A `regex` class matching exactly the characters no consuming item can match, or None.

    An attempt cannot consume a stopper, and every assertion it evaluates sits at or before the
    first stopper at or after its start, so once a stopper follows position t the outcome of the
    attempt at t is final. `\\Z` and non-multiline `$` read the end of the text: no stopper.
    """
    parsed = P.parse(pattern, 0)
    acc: list = []
    if not _collect(parsed, parsed.state.flags, acc):
        return None
    if any(op is C.ANY and fl & C.SRE_FLAG_DOTALL for op, _av, fl in acc):
        return None
    parts: list[str] = []
    for op, av, fl in acc:
        _emit_one(op, av, fl, parts)
    if not parts:
        return None
    return "(?:(?!(?:" + "|".join(dict.fromkeys(parts)) + "))(?s:.))"
