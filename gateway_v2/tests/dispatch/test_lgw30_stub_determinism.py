"""LGW30 stub-determinism property test (GW30, task 7.2).

# Feature: vector-store-adapter-gw30, Property 6: Stub determinism
# Validates: Requirements 4.4, 4.5, 4.6

Property 6 (design §Correctness Properties → Property 6): *for all* seeds and
scripted result/error sequences, two ``Stub_Vector_Connector`` instances
constructed with the **same** injected seed, the **same** scripted
``AdapterResult`` sequence, and the **same** ``Capabilities`` produce
byte-identical outputs across an identical sequence of operation calls — result
codes, records, counts, collections, status, and ``detail_ref`` all equal, in
the same script order — while opening zero sockets or file handles.

This also pins two edges of the replay contract:

* A **different** seed / script does NOT silently change the replay-order
  contract: the stub always returns the scripted results strictly in the order
  they were declared, independent of which of the six operations is called and
  independent of the injected ``random.Random`` (the ``rng`` is retained for
  parity with the real connector's injected-randomness contract but the
  deterministic replay never consumes it).
* **Exhaustion fails closed** with ``PROVIDER_UNREACHABLE`` (``records is None``)
  — never raising, never fabricating an empty success — once the script is spent.

House idiom: a seeded ``random.Random`` drives ``_ITERATIONS`` trials, each trial
GENERATED by ``random.Random(seed)`` and then REPLAYED by two freshly-built stubs
constructed with ``random.Random(same_seed)`` injected, so the test owns the one
deterministic source. No ``hypothesis``; async paths run through ``asyncio.run``.

_Design: Testing Strategy (property tests); Components §Stub_Vector_Connector;
Correctness Properties → Property 6._
_Requirements: 4.4, 4.5, 4.6._
"""

from __future__ import annotations

import asyncio
import random
from collections.abc import Awaitable
from types import MappingProxyType

from gateway_v2.dispatch.vector_adapter import (
    AdapterResult,
    Capabilities,
    CreateRequest,
    DeleteRequest,
    HealthRequest,
    ListRequest,
    QueryRequest,
    UpsertRequest,
    Vector_Adapter,
    VectorRecord,
)
from gateway_v2.dispatch.vector_connectors import Stub_Vector_Connector
from gateway_v2.domain import posture

_ITERATIONS = 10_000

# The six operation names the stub replays across, in no privileged order — the
# generator picks freely so the call sequence interleaves every operation.
_OPERATIONS = (
    "query",
    "upsert",
    "delete",
    "list_collections",
    "create_collection",
    "health",
)

# Every GW30 non-OK posture code a scripted failure result may carry.
_FAILURE_CODES = (
    posture.UNSUPPORTED_OPERATION,
    posture.PROVIDER_UNREACHABLE,
    posture.CREDENTIAL_UNAVAILABLE,
    posture.STORE_NOT_CONFIGURED,
    posture.CREDENTIAL_SCOPE_MISMATCH,
    posture.ORG_IDENTITY_INVALID,
    posture.VECTOR_CAPACITY_EXCEEDED,
    posture.VECTOR_CAPACITY_UNSET,
    posture.CREDENTIAL_LEAK_WITHHELD,
)

# The AdapterResult success variants a script may carry — each exercises a
# different populated field so the byte-identical comparison covers records,
# count, collections, and status, not just the code.
_OK_VARIANTS = ("records", "count", "collections", "status")


def _run[T](coro: Awaitable[T]) -> T:
    """Drive one coroutine to completion (house idiom; no async test plugin)."""
    return asyncio.run(coro)  # type: ignore[arg-type]


def _random_record(rng: random.Random) -> VectorRecord:
    """A deterministic :class:`VectorRecord` from the injected ``rng``."""
    dim = rng.randint(0, 4)
    vector = tuple(rng.uniform(-1.0, 1.0) for _ in range(dim))
    meta = {f"k{i}": rng.randint(0, 9) for i in range(rng.randint(0, 3))}
    return VectorRecord(
        id=f"rec-{rng.randint(0, 1_000_000)}",
        vector=vector,
        metadata=MappingProxyType(meta),
    )


def _random_result(rng: random.Random) -> AdapterResult:
    """A random scripted :class:`AdapterResult` — an OK variant or a failure.

    The variant selection is driven entirely by ``rng`` so that the SAME seed
    reproduces the SAME script byte-for-byte: this is what the determinism
    property compares two stubs against.
    """
    if rng.random() < 0.5:
        variant = rng.choice(_OK_VARIANTS)
        if variant == "records":
            n = rng.randint(0, 4)
            records = tuple(_random_record(rng) for _ in range(n))
            return AdapterResult(code=posture.VECTOR_OK, records=records)
        if variant == "count":
            return AdapterResult(code=posture.VECTOR_OK, count=rng.randint(0, 10_000))
        if variant == "collections":
            cols = tuple(f"col-{rng.randint(0, 999)}" for _ in range(rng.randint(0, 4)))
            return AdapterResult(code=posture.VECTOR_OK, collections=cols)
        # status
        return AdapterResult(
            code=posture.VECTOR_OK,
            status=rng.choice(("reachable", "degraded")),
        )
    # A declared failure: non-OK code, absent records, optional ref id.
    code = rng.choice(_FAILURE_CODES)
    detail_ref = f"cred-ref-{rng.randint(0, 9999)}" if rng.random() < 0.5 else None
    return AdapterResult(code=code, detail_ref=detail_ref)


def _random_capabilities(rng: random.Random) -> Capabilities:
    """A :class:`Capabilities` with all three flags defined from ``rng``."""
    return Capabilities(
        filters=rng.random() < 0.5,
        namespaces=rng.random() < 0.5,
        hybrid_search=rng.random() < 0.5,
    )


def _random_script(rng: random.Random, length: int) -> tuple[AdapterResult, ...]:
    """A scripted result sequence of the given ``length``."""
    return tuple(_random_result(rng) for _ in range(length))


def _random_call_plan(rng: random.Random, n_calls: int) -> tuple[str, ...]:
    """A sequence of ``n_calls`` operation names, interleaving all six ops."""
    return tuple(rng.choice(_OPERATIONS) for _ in range(n_calls))


# Fixed request payloads: the stub replays its script regardless of the request
# values, so these only need to be the right type per operation.
_REQUESTS = {
    "query": QueryRequest(
        org_id="org", store_id="pinecone", collection="c", vector=(0.0,), top_k=1
    ),
    "upsert": UpsertRequest(org_id="org", store_id="pinecone", collection="c", records=()),
    "delete": DeleteRequest(org_id="org", store_id="pinecone", collection="c", ids=()),
    "list_collections": ListRequest(org_id="org", store_id="pinecone"),
    "create_collection": CreateRequest(
        org_id="org", store_id="pinecone", collection="c", dimension=1, metric="cosine"
    ),
    "health": HealthRequest(org_id="org", store_id="pinecone"),
}


async def _invoke(stub: Stub_Vector_Connector, op: str) -> AdapterResult:
    """Await the named operation on ``stub`` with the matching fixed request."""
    if op == "query":
        return await stub.query(_REQUESTS["query"])  # type: ignore[arg-type]
    if op == "upsert":
        return await stub.upsert(_REQUESTS["upsert"])  # type: ignore[arg-type]
    if op == "delete":
        return await stub.delete(_REQUESTS["delete"])  # type: ignore[arg-type]
    if op == "list_collections":
        return await stub.list_collections(_REQUESTS["list_collections"])  # type: ignore[arg-type]
    if op == "create_collection":
        return await stub.create_collection(_REQUESTS["create_collection"])  # type: ignore[arg-type]
    return await stub.health(_REQUESTS["health"])  # type: ignore[arg-type]


async def _replay(stub: Stub_Vector_Connector, plan: tuple[str, ...]) -> list[AdapterResult]:
    """Replay the whole call ``plan`` against one stub, collecting every result."""
    return [await _invoke(stub, op) for op in plan]


def _build_stub(
    seed: int, script: tuple[AdapterResult, ...], caps: Capabilities
) -> Stub_Vector_Connector:
    """Build a stub with a FRESH ``random.Random(seed)`` injected (never shared)."""
    return Stub_Vector_Connector(
        script=script,
        capabilities=caps,
        rng=random.Random(seed),
    )


def test_stub_is_instance_of_runtime_checkable_protocol() -> None:
    """A built ``Stub_Vector_Connector`` satisfies the ``Vector_Adapter`` protocol (R4.4)."""
    stub = _build_stub(0, (), Capabilities(filters=True, namespaces=True, hybrid_search=True))
    assert isinstance(stub, Vector_Adapter)


def test_stub_determinism_byte_identical_across_same_seed_and_script() -> None:
    """Property 6: same seed + same script → byte-identical outputs in script order.

    Each trial is GENERATED by one ``random.Random(trial_seed)`` (script length,
    which result variants appear, the capability flags, and the call sequence),
    then two independent stubs are built with a FRESH ``random.Random(inject_seed)``
    injected into each and driven through the identical call plan. Every produced
    :class:`AdapterResult` must be equal field-for-field between the two stubs, in
    the same order — and the failure-replay edges (order honoured, exhaustion
    fails closed with ``PROVIDER_UNREACHABLE``) must hold.

    _Validates: Requirements 4.4, 4.5, 4.6._
    """
    driver = random.Random(0xA17EC30)

    for _ in range(_ITERATIONS):
        trial_seed = driver.randint(0, 2**63 - 1)
        gen = random.Random(trial_seed)

        script_len = gen.randint(0, 12)
        script = _random_script(gen, script_len)
        caps = _random_capabilities(gen)
        # Deliberately allow MORE calls than script entries so exhaustion is
        # exercised on a meaningful fraction of trials.
        n_calls = gen.randint(0, script_len + 3)
        plan = _random_call_plan(gen, n_calls)

        # Two stubs, SAME injected seed, SAME script, SAME capabilities.
        inject_seed = gen.randint(0, 2**63 - 1)
        stub_a = _build_stub(inject_seed, script, caps)
        stub_b = _build_stub(inject_seed, script, caps)

        out_a = _run(_replay(stub_a, plan))
        out_b = _run(_replay(stub_b, plan))

        # Byte-identical outcomes across the identical call sequence.
        assert out_a == out_b, (
            f"determinism broke at seed={trial_seed}: {out_a!r} != {out_b!r}"
        )

        # capabilities() is identical and verbatim on both stubs.
        assert stub_a.capabilities() == caps
        assert stub_b.capabilities() == caps

        # Replay order is honoured: the first min(len(script), n_calls) results
        # are exactly the scripted entries, in declared order, regardless of
        # which operation consumed them.
        consumed = min(script_len, n_calls)
        assert tuple(out_a[:consumed]) == script[:consumed]

        # Exhaustion fails closed with PROVIDER_UNREACHABLE (records absent),
        # for every call past the end of the script.
        for result in out_a[consumed:]:
            assert result.code == posture.PROVIDER_UNREACHABLE
            assert result.records is None
            assert result.ok is False


def test_different_seed_or_script_preserves_replay_order_contract() -> None:
    """A different seed/script never silently changes the script-order contract (R4.5).

    Whatever the injected seed and whatever the generated script, the stub always
    returns the scripted results strictly in the order declared, then fails closed
    with ``PROVIDER_UNREACHABLE`` on exhaustion. This asserts the ``rng`` does not
    leak into the replay: two stubs with the SAME script but DIFFERENT injected
    seeds still produce identical scripted-order output.

    _Validates: Requirements 4.5, 4.6._
    """
    driver = random.Random(0x5EED00)

    for _ in range(_ITERATIONS):
        trial_seed = driver.randint(0, 2**63 - 1)
        gen = random.Random(trial_seed)

        script_len = gen.randint(1, 12)
        script = _random_script(gen, script_len)
        caps = _random_capabilities(gen)
        n_calls = gen.randint(1, script_len + 3)
        plan = _random_call_plan(gen, n_calls)

        # SAME script, DIFFERENT injected seeds.
        seed_x = gen.randint(0, 2**31 - 1)
        seed_y = seed_x + 1  # guaranteed distinct
        stub_x = _build_stub(seed_x, script, caps)
        stub_y = _build_stub(seed_y, script, caps)

        out_x = _run(_replay(stub_x, plan))
        out_y = _run(_replay(stub_y, plan))

        # The injected seed does not perturb replay: output is identical.
        assert out_x == out_y

        # Output is exactly the scripted prefix followed by fail-closed padding.
        consumed = min(script_len, n_calls)
        expected = list(script[:consumed])
        expected += [
            AdapterResult(code=posture.PROVIDER_UNREACHABLE)
            for _ in range(n_calls - consumed)
        ]
        assert out_x == expected
