_CATEGORIES = tuple(Category)
_ACTIONS = ("allow", "flag", "redact", "block")
_ACTION_DISPOSITION = {
    "allow": Disposition.ALLOW,
    "flag": Disposition.FLAG,
    "redact": Disposition.REDACT,
    "block": Disposition.BLOCK,
}
_RANK = {Disposition.ALLOW: 0, Disposition.FLAG: 1, Disposition.REDACT: 2, Disposition.BLOCK: 3}


def _random_plan(rng: random.Random, index: int) -> ExecutionPlan:
    """A random compiled plan whose every rule is ``scope: both``."""
    rules: list[dict[str, object]] = []
    for category in _CATEGORIES:
        for slot in range(rng.choice((0, 1, 1, 1, 2, 3))):
            rules.append(
                {
                    "rule_id": f"p{index}-{category.value}-{slot}",
                    "category": category.value,
                    "mode": rng.choice(("enforce", "enforce", "monitor", "off")),
                    "action": rng.choice(_ACTIONS),
                    "threshold": None,
                    "priority": rng.choice((10, 50, 50, 100)),
                    "scope": "both",
                    "on_unavailable": rng.choice(("fail_closed", "fail_open")),
                    "surfaces": ["chat", "embeddings"],
                }
            )
    document = {"org_id": ORG, "streaming_mode": "incremental", "rules": rules}
    return _compile(json.dumps(document).encode())


@dataclass(frozen=True, slots=True)
class _Expected:
    disposition: Disposition
    per_finding: tuple[tuple[str, Disposition], ...]
    deciding_rules: tuple[str, ...]
    unavailable: tuple[str, ...]
    redacted: frozenset[int]


def _oracle(findings: Sequence[Finding], plan: ExecutionPlan) -> _Expected:
    """Today's resolver semantics over a ``scope: both`` plan, written out independently.

    Per finding: SKIPPED contributes nothing; UNAVAILABLE -> BLOCK iff an ENFORCE rule of its
    category is ``fail_closed``; EXECUTED -> the action of the highest-priority ENFORCE rule of
    its category (ties: the most restrictive action), ALLOW contributing nothing. The request
    disposition is the most restrictive per-finding disposition; REDACT findings' spans are
    the redacted positions; the deciding rule is the first category rule carrying the winning
    action; UNAVAILABLE detectors are recorded once each, in order.
    """
    per_finding: list[tuple[str, Disposition]] = []
    deciding: list[str] = []
    unavailable: list[str] = []
    redacted: set[int] = set()
    for finding in findings:
        rules = [rule for rule in plan.rules if rule.category == finding.category]
        enforcing = [rule for rule in rules if rule.mode.value == "enforce"]
        if finding.status is FindingStatus.SKIPPED:
            continue
        if finding.status is FindingStatus.UNAVAILABLE:
            if finding.detector not in unavailable:
                unavailable.append(finding.detector)
            if any(rule.on_unavailable.value == "fail_closed" for rule in enforcing):
                per_finding.append((finding.detector, Disposition.BLOCK))
            continue
        if not enforcing:
            continue
        top = max(rule.priority for rule in enforcing)
        tied = [_ACTION_DISPOSITION[r.action.value] for r in enforcing if r.priority == top]
        winner = max(tied, key=lambda item: _RANK[item])
        if winner is Disposition.ALLOW:
            continue
        per_finding.append((finding.detector, winner))
        deciding.extend(
            [rule.rule_id for rule in rules if _ACTION_DISPOSITION[rule.action.value] is winner][:1]
        )
        if winner is Disposition.REDACT:
            for span in finding.spans:
                redacted.update(range(span.start, span.end))
    disposition = max(
        (item for _detector, item in per_finding), key=lambda item: _RANK[item], default=None
    )
    return _Expected(
        disposition=Disposition.ALLOW if disposition is None else disposition,
        per_finding=tuple(per_finding),
        deciding_rules=tuple(deciding),
        unavailable=tuple(unavailable),
        redacted=frozenset(redacted),
    )


def _synthetic(rng: random.Random, text: str) -> Finding:
    status = rng.choice(tuple(FindingStatus))
    category = rng.choice(_CATEGORIES)
    detector = rng.choice(("pii", "secret", "injection", "guard.semantic"))
    if status is not FindingStatus.EXECUTED or not text:
        return Finding(detector, "pres-v1", category, status, None, (), None)
    start = rng.randrange(len(text))
    end = rng.randint(start + 1, len(text))
    return Finding(detector, "pres-v1", category, status, 1.0, (Span(start, end),), None)


def _decision_text(rng: random.Random) -> str:
    """Any detector-reachable mix, REDACT included (the resolver is not the bug site)."""
    plant = _Plant(block=rng.random() < 0.3, pii=rng.random() < 0.4, flags=rng.choice((0, 0, 1, 2)))
    return _channel_text(rng, plant)


def test_scope_both_decisions_equal_todays_for_the_same_findings() -> None:
    """Property 14 (decision level): ``resolve`` at INPUT and OUTPUT equals the frozen oracle.

    10,000 iterations over 64 random ``scope: both`` plans plus the dev plan; findings are the
    real GW09 detectors' (input-phase and output-phase instances) plus synthetic SKIPPED /
    UNAVAILABLE / EXECUTED findings over arbitrary categories. Both phases must equal the
    oracle and each other (the projection compared excludes no field the oracle can predict:
    disposition, per-finding detector + disposition, deciding rules, unavailable detectors,
    redacted positions, every transformation's kind and placeholder, findings, plan version).

    **Validates: Requirements 3.4, 3.5**
    """
    plans = [_DEV_PLAN] + [_random_plan(random.Random(_BASE_SEED - i), i) for i in range(1, 65)]
    for index in range(ITERATIONS):
        seed = _BASE_SEED + index
        rng = random.Random(seed)
        plan = rng.choice(plans)
        text = _decision_text(rng)
        detector = _INPUT_DETECTOR if rng.random() < 0.5 else _OUTPUT_DETECTOR
        findings = list(detector(text))
        for _ in range(rng.choice((0, 0, 1, 2))):
            findings.insert(rng.randint(0, len(findings)), _synthetic(rng, text))
        expected = _oracle(findings, plan)
        decisions = {phase: resolve(findings, plan, phase) for phase in (Phase.INPUT, Phase.OUTPUT)}
        where = f"seed={seed} plan={plan.version} text={text!r}"
        assert decisions[Phase.INPUT] == decisions[Phase.OUTPUT], (
            f"{where}: scope-both INPUT and OUTPUT decisions differ"
        )
        for phase, decision in decisions.items():
            at = f"{where} phase={phase.value}"
            assert decision.disposition is expected.disposition, (
                f"{at}: disposition {decision.disposition} != {expected.disposition}"
            )
            got = tuple((item.detector, item.disposition) for item in decision.per_finding)
            assert got == expected.per_finding, f"{at}: per_finding {got} != {expected.per_finding}"
            assert decision.deciding_rules == expected.deciding_rules, (
                f"{at}: deciding_rules {decision.deciding_rules} != {expected.deciding_rules}"
            )
            assert decision.unavailable_detectors == expected.unavailable, (
                f"{at}: unavailable {decision.unavailable_detectors} != {expected.unavailable}"
            )
            covered: set[int] = set()
            for transformation in decision.transformations:
                assert transformation.kind == "redact", f"{at}: {transformation!r}"
                assert transformation.replacement == REDACTED, f"{at}: {transformation!r}"
                covered.update(range(transformation.span.start, transformation.span.end))
            assert covered == expected.redacted, f"{at}: redacted positions differ"
            assert decision.findings == tuple(findings), f"{at}: findings not recorded as given"
            assert decision.plan_version == plan.version, f"{at}: plan_version"


