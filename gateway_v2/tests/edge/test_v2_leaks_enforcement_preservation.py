class _RecordingProvider:
    """Records the exact ``(channel, text)`` deltas of every forwarded body.

    Chat bodies are answered ``"echo: " + <forwarded texts joined by \\n> + suffix`` in ONE final
    event (``suffix`` is set by the driver before each request, e.g. ``" SSN 123-45-6789"``, so
    the output guard's masking is observable). Embeddings bodies are answered one JSON vector
    ``[index, 0.5]`` per forwarded item, in order.
    """

    def __init__(self) -> None:
        self.received: list[tuple[Delta, ...]] = []
        self.suffix = ""

    def open(self, request: UpstreamRequest) -> AsyncIterator[UpstreamEvent]:
        return self._stream(request)

    async def _stream(self, request: UpstreamRequest) -> AsyncIterator[UpstreamEvent]:
        raw = request.body.get(BODY_DELTAS_KEY, ())
        assert isinstance(raw, tuple)
        deltas = tuple((str(item[0]), str(item[1])) for item in raw)
        self.received.append(deltas)
        if deltas and all(channel == EMB_CHANNEL for channel, _text in deltas):
            for index in range(len(deltas)):
                vector = json.dumps([float(index), 0.5])
                yield UpstreamEvent(
                    text_deltas=((EMB_CHANNEL, vector),), final=index == len(deltas) - 1
                )
            return
        yield UpstreamEvent(text_deltas=(("content", _echo(deltas, self.suffix)),), final=True)

    async def abort(self) -> None:
        return None


def _echo(deltas: Sequence[Delta], suffix: str) -> str:
    return "echo: " + "\n".join(text for _channel, text in deltas) + suffix


