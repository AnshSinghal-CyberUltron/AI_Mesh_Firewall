@dataclass(frozen=True, slots=True)
class _ChatCase:
    seed: int
    body: bytes
    stream: bool
    auth: str | None
    expected: str  # allow | flag | block | malformed | identity
    deltas: tuple[Delta, ...]
    suffix: str


def _chat_case(seed: int) -> _ChatCase:
    rng = random.Random(seed)
    stream = rng.random() < 0.5
    suffix = f" SSN {_ssn(rng)}" if rng.random() < 0.5 else ""
    roll = rng.random()
    if roll < 0.03:
        body = rng.choice((b"{not json", b'{"model": "echo-1", "messages": ['))
        return _ChatCase(seed, body, stream, KEY, "malformed", (), suffix)
    auth: str | None = KEY
    if roll < 0.07:
        auth = rng.choice((None, "sk-wrong-key"))
    channel_count = rng.randint(1, 4)
    expected, plants = _plants(rng, channel_count)
    messages: list[dict[str, object]] = []
    deltas: list[Delta] = []
    remaining = list(plants)
    while remaining:
        role = rng.choice(("system", "user", "assistant", "user"))
        take = 1 if len(remaining) == 1 or rng.random() < 0.6 else rng.randint(2, len(remaining))
        chunk, remaining = remaining[:take], remaining[take:]
        texts = [_channel_text(rng, plant) for plant in chunk]
        if take == 1 and rng.random() < 0.7:
            messages.append({"role": role, "content": texts[0]})
            deltas.append(("message_content", texts[0]))
        else:
            messages.append({"role": role, "content": [{"type": "text", "text": t} for t in texts]})
            deltas.extend(("content_part_text", t) for t in texts)
    body = json.dumps({"model": MODEL, "stream": stream, "messages": messages}).encode()
    if auth != KEY:
        expected = "identity"
    return _ChatCase(seed, body, stream, auth, expected, tuple(deltas), suffix)


async def _drive_chat(app: object, provider: _RecordingProvider, case: _ChatCase) -> None:
    where = f"seed={case.seed} chat stream={case.stream} expected={case.expected}"
    if case.deltas:
        parsed = OpenAIRequestParser().parse(case.body, surface=Surface.CHAT)
        assert parsed.text_deltas == case.deltas, f"{where}: generator deltas != parsed deltas"
        if case.expected in ("allow", "flag", "block"):
            today = _today_class([text for _channel, text in case.deltas])
            assert today == case.expected, f"{where}: generator precondition, today {today!r}"
    provider.suffix = case.suffix
    calls_before = len(provider.received)
    response = await _post(app, CHAT, case.body, auth=case.auth)
    calls = len(provider.received) - calls_before

    if case.expected in ("allow", "flag"):
        assert calls == 1, f"{where}: an ALLOW/FLAG input must make exactly one provider call"
        assert provider.received[-1] == case.deltas, (
            f"{where}: provider deltas {provider.received[-1]!r} != req.text_deltas {case.deltas!r}"
        )
        reply = _echo(case.deltas, case.suffix)
        content = reply.replace(case.suffix, f" SSN {REDACTED}") if case.suffix else reply
        assert response.status == 200, f"{where}: status {response.status}"
        want = _chat_stream_ok(content) if case.stream else _chat_json_ok(content)
        assert response.body == want, f"{where}: output bytes {response.body!r} != {want!r}"
        return

    assert calls == 0, f"{where}: a refused request must make zero provider calls ({calls})"
    if case.expected == "malformed":
        _assert_json_refusal(response, "malformed_request_body", post_identity=False, where=where)
        return
    code = "input_blocked" if case.expected == "block" else "shared_state_unavailable"
    if case.stream:
        _assert_sse_refusal(response, code, where=where)
    else:
        _assert_json_refusal(response, code, post_identity=case.expected == "block", where=where)


def test_chat_enforcement_and_bytes_preserved() -> None:
    """Property 14 (chat): same code/status/request_id echo, same provider and output bytes.

    **Validates: Requirements 3.1, 3.2, 3.3, 3.5, 3.12**
    """
    provider = _RecordingProvider()
    app = _app(_DEV_ENV, provider)
    cases = [_chat_case(_BASE_SEED + index) for index in range(ITERATIONS)]

    async def _run() -> None:
        for case in cases:
            await _drive_chat(app, provider, case)

    asyncio.run(_run())
    seen = {case.expected for case in cases}
    assert seen == {"allow", "flag", "block", "malformed", "identity"}, f"coverage {seen}"


