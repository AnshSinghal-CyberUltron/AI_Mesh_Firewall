_LOWER = "abcdefghijklmnopqrstuvwxyz"


def _block_value(rng: random.Random) -> str:
    """A secret / credential value the dev plan BLOCKs (never a card number)."""
    kind = rng.randrange(5)
    if kind == 0:
        return "key AKIAIOSFODNN7EXAMPLE"
    if kind == 1:
        prefix = rng.choice(("AKIA", "ASIA"))
        return "key " + prefix + "".join(rng.choice(_UPPER) for _ in range(16))
    if kind == 2:
        name = rng.choice(("api_key=", "secret_key: ", "access_token="))
        return name + "".join(rng.choice(_UPPER + _LOWER) for _ in range(rng.randint(16, 28)))
    return rng.choice(
        (
            "-----BEGIN RSA PRIVATE KEY-----",
            "-----BEGIN PRIVATE KEY-----",
            "-----BEGIN OPENSSH PRIVATE KEY-----",
        )
    )


def _pii_value(rng: random.Random) -> str:
    """A PII value the dev plan REDACTs (only ever planted alongside a BLOCK)."""
    if rng.random() < 0.5:
        return (
            f"SSN {rng.randint(100, 899):03d}-{rng.randint(10, 99):02d}-{rng.randint(0, 9999):04d}"
        )
    return f"mail {rng.choice(_BENIGN[:30])}@example.com"


def _ssn(rng: random.Random) -> str:
    return f"{rng.randint(100, 899):03d}-{rng.randint(10, 99):02d}-{rng.randint(1000, 9999):04d}"


def _words(rng: random.Random, low: int, high: int) -> list[str]:
    return [rng.choice(_BENIGN) for _ in range(rng.randint(low, high))]


@dataclass(frozen=True, slots=True)
class _Plant:
    block: bool = False
    pii: bool = False
    flags: int = 0


def _channel_text(rng: random.Random, plant: _Plant) -> str:
    """Benign words, then BLOCK, then PII, then FLAG phrases (a BLOCK precedes every FLAG)."""
    parts = _words(rng, 0 if plant.block or plant.pii or plant.flags else 1, 4)
    if plant.block:
        parts.append(_block_value(rng))
    if plant.pii:
        parts.extend(_words(rng, 0, 2))
        parts.append(_pii_value(rng))
    for _ in range(plant.flags):
        parts.extend(_words(rng, 0, 2))
        parts.append(rng.choice(_FLAG_PHRASES))
    parts.extend(_words(rng, 0, 3))
    return " ".join(parts)


def _plants(rng: random.Random, channels: int) -> tuple[str, tuple[_Plant, ...]]:
    """Choose the request class and spread its plants over ``channels`` channels."""
    roll = rng.random()
    expected = "allow" if roll < 0.3 else "flag" if roll < 0.6 else "block"
    plants = [_Plant() for _ in range(channels)]

    def _add(index: int, *, block: bool = False, pii: bool = False, flags: int = 0) -> None:
        old = plants[index]
        plants[index] = _Plant(
            block=old.block or block, pii=old.pii or pii, flags=old.flags + flags
        )

    if expected == "flag":
        for _ in range(rng.randint(1, 2)):
            _add(rng.randrange(channels), flags=1)
    if expected == "block":
        _add(rng.randrange(channels), block=True)
        if rng.random() < 0.5:  # BLOCK co-occurring with REDACT (same or another channel)
            _add(rng.randrange(channels), pii=True)
        if rng.random() < 0.5:  # BLOCK co-occurring with FLAG
            _add(rng.randrange(channels), flags=1)
        if rng.random() < 0.2:
            _add(rng.randrange(channels), block=True)
    return expected, tuple(plants)


