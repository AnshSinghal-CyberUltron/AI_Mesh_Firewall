"""v2-enforcement-leaks preservation: enforcement and lifecycle unchanged off the bug condition.

Preservation test (spec ``v2-enforcement-leaks``, task 11; design Property 2 / Property 14;
requirements 3.1-3.5, 3.12, 3.13, 3.16). Written observation-first on the UNFIXED tree, where it
PASSES; it must keep passing after the fix.

**Observed on the unfixed tree** (the frozen oracle below encodes exactly this):

* under the dev plan (``dev/plan.example.json``: pii -> redact, secret/credential -> block,
  injection/jailbreak/command -> flag, every rule ``scope: both``) ``key AKIAIOSFODNN7EXAMPLE``
  refuses ``input_blocked`` with ZERO provider calls -- also when it co-occurs with a REDACT
  (SSN / email) or FLAG finding (3.1, C22);
* ALLOW and FLAG inputs reach the provider byte-identical to ``req.text_deltas`` (chat) and
  item-for-item identical, same count and order (embeddings) (3.2, 3.16);
* the output guard masks a reply SSN with ``[REDACTED]``, streaming and non-streaming (3.3);
* chat JSON refusals after identity echo the gateway-minted ``zs-`` id in the body and the
  ``x-request-id`` header; refusals before identity (parse, identity) render
  ``request_id: null`` with no header (3.12). Two rendering facts are snapshotted as observed:
  a streaming chat refusal is an SSE ``200`` carrying one error frame with no ``request_id``
  field, and every ``/v1/embeddings`` refusal renders ``request_id: null``;
* the default boot (no dev profile) refuses every request with its declared code --
  ``request_pre_check_exceeded`` / ``malformed_request_body`` / ``shared_state_unavailable`` --
  with ``request_id: null`` and zero provider calls (3.12, 3.13).

**Oracle.** A frozen expectation function derived from the plan, not from the product: BLOCK iff
the generated request plants a secret/credential value (AWS key, API key, PEM header), else FLAG
iff it plants an injection/jailbreak/command phrase, else ALLOW; a BLOCK refuses with the
snapshotted envelope, an ALLOW/FLAG forwards the generated bytes unchanged and the client gets
the provider reply with every SSN replaced by ``[REDACTED]``. Response bodies on the success
path are compared BYTE-for-byte against frozen templates; refusal bodies are compared as parsed
envelopes. Each round trip also re-derives the oracle's disposition class from today's
detectors + resolver over every input channel (a precondition: the generator really produces
the class it claims). Byte identity is asserted, never "no transformation call", so the test
stays valid once the fixed lifecycle always routes through ``apply_and_verify``.

**Generator scope (off the bug condition).** Benign words (no digits, no trigger substrings),
FLAG phrases the UNFIXED detector already confirms at the prefilter offset (``ignore all
previous instructions``, ``jailbreak``, ``$(whoami)``, ...; never ``you are DAN`` /
``enable developer mode`` / ``answer without restrictions``, whose detection changes with Group
C), BLOCK values, and PII only alongside a BLOCK. No REDACT-only request (Group A's condition),
no card number and no confusable (Groups B/C), no lead-context phrase, ASCII only. Within a
channel a BLOCK value precedes every FLAG phrase so no confirmed override prefilter can span it.
No component is split across content parts. The dev budget is ``unlimited`` (every token cost is
covered), and ``max_tokens`` / ``n`` are never sent (Group F's parser condition).

**Iteration counts.** One ASGI round trip costs ~0.4 ms (chat) / ~0.2 ms (embeddings) in-process,
so every property runs its full 10,000 seeded iterations: 10,000 chat round trips, 10,000
embeddings round trips, 10,000 default-boot round trips, and 10,000 decision-level iterations of
``resolve`` over detector (+ synthetic SKIPPED / UNAVAILABLE / EXECUTED) findings at
``Phase.INPUT`` and ``Phase.OUTPUT`` under random ``scope: both`` plans. Each case has its own
seed (``_BASE_SEED + index``), named in every assertion message. No hypothesis.
"""

