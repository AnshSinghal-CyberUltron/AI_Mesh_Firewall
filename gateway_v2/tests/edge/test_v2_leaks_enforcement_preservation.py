def _compact(value: object) -> bytes:
    return json.dumps(value, separators=(",", ":")).encode()


def _chat_json_ok(content: str) -> bytes:
    return _compact(
        {
            "id": "chatcmpl-gateway",
            "object": "chat.completion",
            "created": 0,
            "model": MODEL,
            "choices": [
                {
                    "index": 0,
                    "message": {"role": "assistant", "content": content},
                    "finish_reason": "stop",
                }
            ],
            "usage": {"prompt_tokens": 0, "completion_tokens": 0, "total_tokens": 0},
        }
    )


def _chat_stream_ok(content: str) -> bytes:
    chunk = _compact(
        {
            "id": "chatcmpl-stream",
            "object": "chat.completion.chunk",
            "created": 0,
            "model": "gateway",
            "choices": [{"index": 0, "delta": {"content": content}, "finish_reason": None}],
        }
    )
    trace = _compact({"produced_mode": "incremental", "degenerated_to_strict": True})
    return b"data: " + chunk + b"\n\nevent: amf.trace\ndata: " + trace + b"\n\ndata: [DONE]\n\n"


