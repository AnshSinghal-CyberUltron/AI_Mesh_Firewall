@dataclass(frozen=True, slots=True)
class _Response:
    status: int
    headers: Headers
    body: bytes


async def _post(app: object, path: str, body: bytes, *, auth: str | None) -> _Response:
    headers = [(b"content-type", b"application/json")]
    if auth is not None:
        headers.append((b"authorization", f"Bearer {auth}".encode()))
    scope = {"type": "http", "method": "POST", "path": path, "headers": headers}
    sent: list[Mapping[str, object]] = []
    delivered = False

    async def _receive() -> Mapping[str, object]:
        nonlocal delivered
        if delivered:
            await asyncio.sleep(3600)
        delivered = True
        return {"type": "http.request", "body": body, "more_body": False}

    async def _send(message: Mapping[str, object]) -> None:
        sent.append(message)

    assert callable(app)
    await app(scope, _receive, _send)
    start = next(m for m in sent if m["type"] == "http.response.start")
    raw_headers = start.get("headers", ())
    assert isinstance(raw_headers, (list, tuple))
    response_headers = {bytes(k).decode(): bytes(v).decode() for k, v in raw_headers}
    payload = b"".join(
        bytes(chunk)
        for m in sent
        if m["type"] == "http.response.body"
        and isinstance(chunk := m.get("body", b""), (bytes, bytearray))
    )
    return _Response(status=int(str(start["status"])), headers=response_headers, body=payload)


